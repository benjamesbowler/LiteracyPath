import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { prepareAssessmentLedaRetirement, assessmentLedaMapSource, parseAssessmentLedaMapSource } from '../../tools/assessmentLedaRetirement.mjs';

const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const audio = Buffer.from('original synthesis bytes');
const row = { role:'isolated_word', key:'hem', publicPath:'/audio/production/en-US/isolated_word/hem-123.mp3', sha256:digest(audio), reason:'Replaced authoring; no remaining required cue.' };
const map = { isolated_word:{ hem:row.publicPath, bell:'/audio/production/en-US/isolated_word/bell-456.mp3' } };
const mapBytes = Buffer.from(assessmentLedaMapSource(map, 'Leda'));
const worklist = { scope:'assessment-leda-exact-retirement', expectedMapSha256:digest(mapBytes), records:[row] };
const dependencies = { map, mapBytes, readAudio:async () => audio, references:[] };

test('retirement parses exact generated bytes without executing input or reusing cached imports', () => {
  assert.deepEqual(parseAssessmentLedaMapSource(mapBytes), map);
  const newer = { ...map, assessment_prompt:{ changed:'/new.mp3' } };
  assert.deepEqual(parseAssessmentLedaMapSource(assessmentLedaMapSource(newer, 'Leda')), newer);
  assert.throws(() => parseAssessmentLedaMapSource('export const x = process.exit(1);'), /Unsupported/);
  assert.throws(() => parseAssessmentLedaMapSource('export const ASSESSMENT_LEDA_GAP_AUDIO_BY_ROLE = Object.freeze({ x: process.exit(1) });'), /JSON|Unexpected|property/);
});

test('retirement removes only the exact unused binding and retains original bytes without mutating input', async () => {
  const result = await prepareAssessmentLedaRetirement(worklist, dependencies);
  assert.deepEqual(result.nextMap, { isolated_word:{ bell:map.isolated_word.bell } });
  assert.equal(map.isolated_word.hem, row.publicPath);
  assert.deepEqual(result.records[0].bytes, audio);
});

test('retirement rejects live or frozen references, aliases, stale maps and changed delivered audio', async () => {
  await assert.rejects(prepareAssessmentLedaRetirement(worklist, { ...dependencies, references:[{ path:row.publicPath+'#clip', source:'frozen-v1' }] }), /still referenced.*frozen-v1/);
  await assert.rejects(prepareAssessmentLedaRetirement(worklist, { ...dependencies, map:{ isolated_word:{ ...map.isolated_word, alias:row.publicPath } } }), /another map owner/);
  await assert.rejects(prepareAssessmentLedaRetirement(worklist, { ...dependencies, mapBytes:Buffer.from('changed') }), /map changed/);
  await assert.rejects(prepareAssessmentLedaRetirement(worklist, { ...dependencies, map:{ isolated_word:{ hem:'/changed.mp3' } } }), /mapping changed/);
  await assert.rejects(prepareAssessmentLedaRetirement(worklist, { ...dependencies, readAudio:async () => Buffer.from('changed') }), /bytes changed/);
});

test('retirement refuses broad, malformed, duplicate and traversal worklists', async () => {
  for (const invalid of [
    { ...worklist, scope:'all' }, { ...worklist, records:[] },
    { ...worklist, records:[row,row] },
    { ...worklist, records:[{ ...row, key:'Hem' }] },
    { ...worklist, records:[{ ...row, reason:'' }] },
    { ...worklist, records:[{ ...row, publicPath:'/audio/production/en-US/isolated_word/../../private.mp3' }] },
  ]) await assert.rejects(prepareAssessmentLedaRetirement(invalid, dependencies), /Invalid|Repeated/);
  await assert.rejects(prepareAssessmentLedaRetirement(worklist, { ...dependencies, references:undefined }), /reference inventory/);
});
