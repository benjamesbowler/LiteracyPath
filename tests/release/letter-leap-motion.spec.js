import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
const motion=page=>page.evaluate(()=>document.querySelector('.letter-leap').__letterLeapMotion());
test('Letter Leap native taps, held jump, interpolated contact and paused resume',async({page},info)=>{
  test.setTimeout(45000);
  await page.setViewportSize({width:1024,height:768});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/preview/game-overlay.html?game=letter-leap&difficulty=easy&sound=0&music=0&review=clear-start');
  await page.waitForFunction(()=>document.querySelector('.letter-leap')?.__letterLeapMotion);
  await page.waitForTimeout(1200);
  const initial=await motion(page);
  await page.keyboard.press('ArrowRight');
  await expect.poll(async()=>(await motion(page)).player.x).toBeGreaterThan(initial.player.x);
  await page.waitForTimeout(150);
  const tapped=await motion(page);expect(tapped.player.x-initial.player.x).toBeLessThan(10);
  await page.keyboard.down('ArrowRight');await page.waitForTimeout(240);await page.keyboard.up('ArrowRight');
  await page.keyboard.down('Space');await page.waitForTimeout(180);await page.keyboard.up('Space');
  const airborne=await motion(page);expect(airborne.player.onGround).toBe(false);
  await page.screenshot({path:info.outputPath('airborne.png')});
  await page.keyboard.press('Escape');
  await expect(page.getByRole('heading',{name:'Leave this game?'})).toBeVisible();
  await page.waitForTimeout(100);const paused=await motion(page);
  await page.waitForTimeout(200);expect((await motion(page)).player).toEqual(paused.player);
  await page.getByRole('button',{name:'Keep playing',exact:true}).click();
  await expect.poll(async()=>(await motion(page)).player.onGround).toBe(true);
  const landed=await motion(page);
  expect(Math.abs(landed.player.y+landed.player.h/2-landed.groundY)).toBeLessThan(.01);
  expect(Math.abs(landed.presentation.player.y-landed.player.y)).toBeLessThan(.01);
  expect(landed.wrongHits).toBe(initial.wrongHits);
  await page.screenshot({path:info.outputPath('ground-contact.png')});
  await fs.writeFile(info.outputPath('motion-states.json'),JSON.stringify({initial,tapped,airborne,paused,landed,errors},null,2));
  expect(errors).toEqual([]);
});
