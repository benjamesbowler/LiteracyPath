import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { LITERACY_QUARANTINED_ITEM_IDS, literacyItemQualityIssue } from '../src/policy/literacyItemEligibility.js';
import { LITERACY_V9_RHYME_QUARANTINE } from '../src/policy/literacyMockRhymeDemandReview.js';

export const V9_RHYME_QUARANTINE_MIGRATION = '20261016174740_literacy_mock_v9_rhyme_demand_quarantine.sql';
const target = new URL(`../supabase/migrations/${V9_RHYME_QUARANTINE_MIGRATION}`, import.meta.url);
const sqlText = value => `'${String(value).replace(/'/g, "''")}'`;

/** Rebuild the shared quality overlay from its current authoring authority.
 * Existing global defects retain their exact issues. The new rhyme defect is
 * contextual: the same source at its older published demand is not withdrawn. */
export function literacyMockV9RhymeQuarantineSql() {
  const rows = [
    ...LITERACY_QUARANTINED_ITEM_IDS.map(id => ({ id, issue: literacyItemQualityIssue({ id }), v9: false })),
    ...LITERACY_V9_RHYME_QUARANTINE.map(row => ({ ...row, v9: true })),
  ];
  const values = rows.map(({ id, issue, v9 }) => `  (${sqlText(id)},${sqlText(JSON.stringify(issue))}::jsonb,${v9})`).join(',\n');
  return `-- Generated by tools/generateLiteracyMockV9RhymeQuarantine.mjs.
-- Selection/reporting overlay only. Published V1–V9 JSON and raw learner answers
-- stay immutable. Existing content-response projections make affected V9
-- answers unscored; older demand metadata retains its previous validity.
begin;
create or replace function public.lp_literacy_item_quality_issue(p_value jsonb)
returns jsonb language sql immutable set search_path='' as $$
 with source as (select coalesce(p_value->'itemSnapshot',p_value->'questionSnapshot',p_value->'question',p_value) s),
 reviewed(id,issue,v9_only) as (values
${values})
 select reviewed.issue from reviewed cross join source
 where reviewed.id=any(array[p_value->>'questionId',p_value->>'id',s->>'id',p_value->>'sourceItemId',s->>'sourceItemId'])
  and (not reviewed.v9_only or (s->>'adaptiveAreaVersion'='areas-v5' and s->'adaptiveAreaBand'='2'::jsonb))
 limit 1;
$$;
revoke all on function public.lp_literacy_item_quality_issue(jsonb) from public,anon,authenticated;
commit;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sql = literacyMockV9RhymeQuarantineSql();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== sql) throw Error('The V9 rhyme quarantine migration is stale.');
  } else fs.writeFileSync(target, sql);
}
