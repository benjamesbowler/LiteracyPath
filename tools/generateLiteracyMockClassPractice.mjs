import { readFile, writeFile } from 'node:fs/promises';
import { loadLiteracyMockV13Candidates } from '../src/data/literacyMockBank.js';
import { partitionLiteracyMockV13 } from '../src/data/literacyMockPracticePartition.js';

const { practice } = partitionLiteracyMockV13(await loadLiteracyMockV13Candidates());
const snapshots = practice.map(item => item.itemSnapshot);
const content = '// Generated by tools/generateLiteracyMockClassPractice.mjs. Practice-only V13 families.\n'
  + `const snapshots = [\n${snapshots.map(item => `  ${JSON.stringify(item)}`).join(',\n')}\n];\n`
  + 'export const LITERACY_MOCK_CLASS_PRACTICE = snapshots.map(snapshot => ({ ...snapshot, itemSnapshot: snapshot }));\n';
const target = new URL('../src/data/generated/literacyMockClassPractice.generated.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== content) throw new Error('The Mock MAP class-practice bank is stale.');
} else await writeFile(target, content);
console.log(`${practice.length} class-practice items.`);
