import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {COMPREHENSION_PICTURES as authored} from './authoring/comprehensionPictures.mjs';

const source=await fs.readFile(new URL('./authoring/comprehensionPictures.mjs',import.meta.url),'utf8');
const tail=source.slice(source.indexOf('\nexport function passagePicture'));
assert.ok(tail.includes('export function passagePicture'));
const metadata=Object.fromEntries(Object.entries(authored).map(([id,record])=>{const value={...record};delete value.prompt;return [id,value];}));
const text='// Generated by tools/generateComprehensionPictures.mjs; edit authoring source instead.\nexport const COMPREHENSION_PICTURES = '+JSON.stringify(metadata,null,2)+';\n'+tail;
const target=new URL('../src/content/comprehension/pictures.js',import.meta.url);
if(process.argv.includes('--check'))assert.equal(await fs.readFile(target,'utf8'),text,'Picture runtime metadata is stale. Run generate:comprehension-pictures.');
else {const temporary=new URL(target.href+'.tmp');await fs.writeFile(temporary,text);await fs.rename(temporary,target);}
console.log(`${Object.keys(metadata).length} picture metadata records ${process.argv.includes('--check')?'verified':'generated'}; generation prompts stay outside learner code.`);
