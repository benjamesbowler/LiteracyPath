import fs from 'node:fs';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createLiteracyMockManifest, compactIncomingSql } from './generateLiteracyMockManifest.mjs';

export const V12_SCHEMA_MIGRATION = '20261028040100_literacy_mock_beginner_v12.sql';
export const V12_CATALOGUE_MIGRATION = '20261028040101_literacy_mock_catalogue_v12.sql';
const root = new URL('../', import.meta.url);
const extend = source => source
  .replace(/\bin\s*\(([^()]*'literacy-mock-v11'[^()]*)\)/gi, (whole, values) => whole.replace(values, `${values},'literacy-mock-v12'`))
  .replace(/\b(p_version|v_version|content_version)\s*=\s*'literacy-mock-v11'/g, "$1 in ('literacy-mock-v11','literacy-mock-v12')");

// Reuse the already verified V11 progression, budgets, receipts and access
// checks. Only version dispatch expands; V1–V11 publications stay immutable.
export function literacyMockV12SchemaSql() {
  const previous = fs.readFileSync(new URL('supabase/migrations/20261020030000_literacy_mock_progression_v11.sql', root), 'utf8');
  const definitions = [...previous.matchAll(/create or replace function public\.(\w+)\([\s\S]*?\$\$;/g)];
  const parts = ['-- Generated by tools/generateLiteracyMockV12.mjs. Familiar beginner vocabulary; unchanged V11 progression.\nbegin;'];
  parts.push(extend(previous.slice(previous.indexOf('alter table'), previous.indexOf('create or replace function'))));
  for (const [, name] of definitions) assert.ok(name);
  for (const [source, name] of definitions) {
    if (!source.includes('literacy-mock-v11') && name !== 'teacher_prepare_literacy_mock_session_v11') continue;
    const preparation = ['lp_mock_prepare_v11_before_delivery','teacher_prepare_literacy_mock_session_v11'].includes(name);
    const next = preparation ? source.replaceAll('v11', 'v12') : extend(source);
    parts.push(next);
    const args = source.match(/function public\.\w+\(([\s\S]*?)\)\s*returns/)[1];
    const types = args.split(',').map(value=>value.trim()).filter(Boolean)
      .map(value=>value.replace(/\s+default\b[\s\S]*/i,'').replace(/^\w+\s+/,'').trim());
    const signature = `public.${preparation ? name.replaceAll('v11','v12') : name}(${types.join(',')})`;
    const roles = name.startsWith('student_') ? 'anon,authenticated' : name.startsWith('teacher_') ? 'authenticated' : null;
    parts.push(`revoke all on function ${signature} from public,anon,authenticated;${roles ? `\ngrant execute on function ${signature} to ${roles};` : ''}`);
  }
  parts.push("notify pgrst,'reload schema';\ncommit;\n");
  return parts.join('\n\n');
}

export async function literacyMockV12CatalogueSql() {
  const manifest = await createLiteracyMockManifest({contentVersion:'literacy-mock-v12'});
  const previous = await createLiteracyMockManifest({contentVersion:'literacy-mock-v11'});
  const byId = new Map(previous.items.map(item=>[item.id,item]));
  const additions = manifest.items.filter(item=>!byId.has(item.id)), patches = {};
  for (const item of manifest.items) {
    const old = byId.get(item.id);
    if (!old) continue;
    for (const key of Object.keys(old).filter(key=>key!=='itemSnapshot')) assert.deepEqual(item[key],old[key],`V12 changed inherited ${item.id} ${key}`);
    for (const key of Object.keys(old.itemSnapshot)) assert.ok(Object.hasOwn(item.itemSnapshot,key));
    const patch = Object.fromEntries(Object.entries(item.itemSnapshot).filter(([key,value])=>key!=='contentVersion' && JSON.stringify(value)!==JSON.stringify(old.itemSnapshot[key])));
    if (Object.keys(patch).length) patches[item.id] = patch;
  }
  const literal = `'${JSON.stringify(patches).replaceAll("'","''")}'::jsonb`;
  return `-- Generated by tools/generateLiteracyMockV12.mjs. New immutable publication; no old catalogue changes.
begin;
create temporary table literacy_mock_incoming(item jsonb not null) on commit drop;
${compactIncomingSql(additions)}
with source as (select item,item->'itemSnapshot' snapshot from public.literacy_mock_items where content_version='literacy-mock-v11'),
route as (select ${literal} patches)
insert into literacy_mock_incoming select jsonb_set(item,'{itemSnapshot}',snapshot||jsonb_build_object('contentVersion','literacy-mock-v12')||coalesce(patches->(snapshot->>'id'),'{}'::jsonb)) from source cross join route;
do $$begin
 if exists(select 1 from literacy_mock_incoming incoming join public.literacy_mock_items old on old.id=incoming.item->>'id' and old.content_version='literacy-mock-v12' where old.item is distinct from incoming.item) then raise exception 'Cannot rewrite immutable V12 publication'; end if;
 if exists(select 1 from public.literacy_mock_publications where content_version='literacy-mock-v12' and item_count<>${manifest.itemCount}) then raise exception 'Published mock catalogue count is immutable'; end if;
end; $$;
insert into public.literacy_mock_items(id,content_version,item) select item->>'id','literacy-mock-v12',item from literacy_mock_incoming on conflict(id,content_version) do nothing;
insert into public.literacy_mock_publications(content_version,item_count) values('literacy-mock-v12',${manifest.itemCount}) on conflict(content_version) do nothing;
do $$begin
 if (select count(*) from public.literacy_mock_items where content_version='literacy-mock-v12')<>${manifest.itemCount} then raise exception 'Incomplete V12 publication'; end if;
end; $$;
notify pgrst,'reload schema';
commit;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [name, sql] of [[V12_SCHEMA_MIGRATION,literacyMockV12SchemaSql()], [V12_CATALOGUE_MIGRATION,await literacyMockV12CatalogueSql()]]) {
    const target = new URL(`supabase/migrations/${name}`,root);
    if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target,'utf8'),sql);
    else fs.writeFileSync(target,sql);
    console.log(`${name}: ${Buffer.byteLength(sql)} bytes; local publication only.`);
  }
}
