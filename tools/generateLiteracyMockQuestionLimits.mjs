import fs from 'node:fs';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { LITERACY_MOCK_SHORT_ITEM_COUNTS } from '../src/policy/literacyMockQuestionLimit.js';

export const MOCK_QUESTION_LIMIT_MIGRATION = '20261106055449_literacy_mock_question_limits.sql';
const source = fs.readFileSync(new URL('../supabase/migrations/20261028040100_literacy_mock_beginner_v12.sql', import.meta.url), 'utf8');
const definitions = new Map([...source.matchAll(/create or replace function public\.(\w+)\([\s\S]*?\$\$;/g)].map(([text, name]) => [name, text]));
const replace = (source, before, after) => {
  assert.ok(source.includes(before), `Missing frozen SQL anchor: ${before}`);
  return source.replace(before, after);
};

export function literacyMockQuestionLimitsSql() {
  const choices = [...LITERACY_MOCK_SHORT_ITEM_COUNTS, 124].join(',');
  const historicalAndCurrentCounts = [...new Set([24,43,67,124,...LITERACY_MOCK_SHORT_ITEM_COUNTS])].sort((a,b)=>a-b).join(',');
  let prepare = replace(definitions.get('lp_mock_prepare_v12_before_delivery'), 'p_item_count<>124', `p_item_count not in (${choices})`);
  let validate = replace(definitions.get('lp_mock_boundary_plan_error_v9'), "v_ordinals jsonb:='{}';", "v_limit integer; v_ordinals jsonb:='{}';");
  validate = replace(validate, 'begin\n if p_answered', `begin
 select item_count into v_limit from public.literacy_mock_sessions where session_id=p_session_id;
 if v_limit is null then return 'invalid_plan'; end if;
 if p_answered`);
  validate = replace(validate, "(case when v_version in ('literacy-mock-v11','literacy-mock-v12') then 124 else 67 end)", 'v_limit');
  validate = replace(validate, 'v_schedule:=public.lp_mock_boundary_schedule_for_version(v_reserved,', 'v_schedule:=public.lp_mock_session_boundary_schedule(p_session_id,v_reserved,');
  let event = replace(definitions.get('student_record_literacy_mock_event'), "public.lp_mock_boundary_schedule_for_version(v_rows,v_states,v_mock->>'content_version')", "public.lp_mock_session_boundary_schedule(p_session_id,v_rows,v_states,v_mock->>'content_version')");
  return `-- Generated by tools/generateLiteracyMockQuestionLimits.mjs.
-- V12 short sittings cap the existing route; no item, response or progression threshold changes.
begin;
alter table public.literacy_mock_sessions drop constraint if exists literacy_mock_sessions_item_count_check;
alter table public.literacy_mock_sessions add constraint literacy_mock_sessions_item_count_check
 check((plan_kind='mixed' and item_count in (${historicalAndCurrentCounts})) or (plan_kind='fresh_check' and item_count between 1 and 6));

create or replace function public.lp_mock_session_boundary_schedule(p_session_id uuid,p_rows jsonb,p_states jsonb,p_version text)
returns jsonb language sql stable set search_path='' as $$
 select coalesce(jsonb_agg(value order by position),'[]'::jsonb)
 from jsonb_array_elements(public.lp_mock_boundary_schedule_for_version(p_rows,p_states,p_version)) with ordinality scheduled(value,position)
 where position <= (select item_count from public.literacy_mock_sessions where session_id=p_session_id);
$$;
revoke all on function public.lp_mock_session_boundary_schedule(uuid,jsonb,jsonb,text) from public,anon,authenticated;

${prepare}
revoke all on function public.lp_mock_prepare_v12_before_delivery(uuid,uuid[],boolean,integer,integer,text,text) from public,anon,authenticated;

${validate}
revoke all on function public.lp_mock_boundary_plan_error_v9(uuid,uuid,jsonb,jsonb,integer,jsonb) from public,anon,authenticated;

${event}
revoke all on function public.student_record_literacy_mock_event(text,uuid,text,text,text) from public,anon,authenticated;
grant execute on function public.student_record_literacy_mock_event(text,uuid,text,text,text) to anon,authenticated;
notify pgrst,'reload schema';
commit;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL(`../supabase/migrations/${MOCK_QUESTION_LIMIT_MIGRATION}`, import.meta.url);
  if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target,'utf8'), literacyMockQuestionLimitsSql());
  else fs.writeFileSync(target, literacyMockQuestionLimitsSql());
}
