import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const migration = 'supabase/migrations/20261016080840_literacy_mock_plan_freshness_cache.sql';
const applied = fs.readFileSync(new URL('supabase/migrations/20261016062452_literacy_mock_retake_v8.sql', root), 'utf8');
const originalSave = applied.match(/create or replace function public\.student_save_literacy_mock_run\([\s\S]*?end; \$\$;/)[0];

function replaceOnce(source, before, after) {
  if (source.split(before).length !== 2) throw Error('The frozen save definition no longer matches its freshness-cache patch.');
  return source.replace(before, after);
}

/** Forward-only optimization: the same canonical history is read once per
 * authorized save, only when an unseen candidate actually needs checking.
 * Every item/passage/family reason, including legacy aliases, stays unchanged. */
export function literacyMockFreshnessCacheSql() {
  const matcher = `create or replace function public.lp_literacy_familiarity_from_exposures(p_exposures jsonb,p_item jsonb)
returns jsonb language sql immutable set search_path='' as $$
  with target as (select public.lp_literacy_exposure_identity(p_item) identity), matches as (
    select key from target cross join lateral jsonb_each_text(identity) t(key,value)
    where t.value<>'' and exists(select 1 from jsonb_array_elements(p_exposures) prior where prior->>t.key=t.value))
  select coalesce(jsonb_agg(case key when 'exposureItemId' then 'item' when 'exposurePassageKey' then 'passage' else 'family' end order by key),'[]'::jsonb) from matches;
$$;`;
  let save = replaceOnce(originalSave, 'v_version text; v_familiarity jsonb;', 'v_version text; v_familiarity jsonb; v_prior jsonb;');
  save = replaceOnce(save, `      if v_version in ('literacy-mock-v3','literacy-mock-v4','literacy-mock-v5','literacy-mock-v6','literacy-mock-v7','literacy-mock-v8') and v_mock->>'fresh_sampling'='true' and v_index>v_count
        and (v_run.session_id is null or v_id is distinct from v_run.plan->'itemIds'->>(v_index-1))
        and not exists(select 1 from public.literacy_mock_events where session_id=p_session_id and student_id=v_student.id and question_id=v_id and event_type='presented')
        and jsonb_array_length(public.lp_literacy_familiarity(v_student.id,v_item))>0 then
        return json_build_object('ok',false,'error','fresh_item_exposed'); end if;`,
  `      if v_version in ('literacy-mock-v3','literacy-mock-v4','literacy-mock-v5','literacy-mock-v6','literacy-mock-v7','literacy-mock-v8') and v_mock->>'fresh_sampling'='true' and v_index>v_count
        and (v_run.session_id is null or v_id is distinct from v_run.plan->'itemIds'->>(v_index-1))
        and not exists(select 1 from public.literacy_mock_events where session_id=p_session_id and student_id=v_student.id and question_id=v_id and event_type='presented') then
        if v_prior is null then v_prior:=public.lp_literacy_exposures(v_student.id); end if;
        if jsonb_array_length(public.lp_literacy_familiarity_from_exposures(v_prior,v_item))>0 then
          return json_build_object('ok',false,'error','fresh_item_exposed'); end if;
      end if;`);
  save = replaceOnce(save, `        if v_index>v_count and not exists(select 1 from public.literacy_mock_events where session_id=p_session_id and student_id=v_student.id and question_id=v_id and event_type='presented')
          and jsonb_array_length(public.lp_literacy_familiarity(v_student.id,v_item))>0 then
          return json_build_object('ok',false,'error','fresh_item_exposed'); end if;`,
  `        if v_index>v_count and not exists(select 1 from public.literacy_mock_events where session_id=p_session_id and student_id=v_student.id and question_id=v_id and event_type='presented') then
          if v_prior is null then v_prior:=public.lp_literacy_exposures(v_student.id); end if;
          if jsonb_array_length(public.lp_literacy_familiarity_from_exposures(v_prior,v_item))>0 then
            return json_build_object('ok',false,'error','fresh_item_exposed'); end if;
        end if;`);
  return `-- Generated by tools/generateLiteracyMockFreshnessCache.mjs.
-- Preserve all published content, evidence, freshness rules and RPC grants.
begin;

${matcher}

revoke all on function public.lp_literacy_familiarity_from_exposures(jsonb,jsonb) from public,anon,authenticated;

${save}

commit;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sql = literacyMockFreshnessCacheSql(), path = new URL(migration, root);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(path, 'utf8') !== sql) throw Error('Stale generated freshness-cache migration.');
  } else fs.writeFileSync(path, sql);
  console.log('Forward freshness-cache migration matches its source.');
}
