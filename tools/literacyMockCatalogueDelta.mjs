import { compactIncomingSql, createLiteracyMockManifest } from './generateLiteracyMockManifest.mjs';

const quote = value => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;

export async function literacyMockCatalogueDelta(from, to) {
  const priorLabel = 'V' + from;
  const label = 'V' + to;
  const [previous, manifest] = await Promise.all([`literacy-mock-v${from}`, `literacy-mock-v${to}`]
    .map(contentVersion => createLiteracyMockManifest({ contentVersion })));
  const byId = new Map(previous.items.map(item => [item.id, item]));
  const inherited = new Set();
  const corrected = manifest.items.filter(item => {
    const old = byId.get(item.id);
    if (!old || JSON.stringify(item) !== JSON.stringify({ ...old,
      itemSnapshot: { ...old.itemSnapshot, contentVersion: manifest.contentVersion } })) return true;
    inherited.add(item.id);
    return false;
  });
  const excluded = previous.items.filter(item => !inherited.has(item.id)).map(item => item.id);
  return `-- Generated by tools/generateLiteracyMock${label}Catalogue.mjs. Unified assessment bank for both entry points.
begin;
create temporary table literacy_mock_incoming(item jsonb not null) on commit drop;
${compactIncomingSql(corrected)}
insert into literacy_mock_incoming
select jsonb_set(item,'{itemSnapshot,contentVersion}','"${manifest.contentVersion}"'::jsonb)
from public.literacy_mock_items where content_version='${previous.contentVersion}'
 and not (${quote(excluded)} ? id);
do $$begin
 if (select count(*) from literacy_mock_incoming) <> ${manifest.itemCount}
  or (select count(distinct item->>'id') from literacy_mock_incoming) <> ${manifest.itemCount} then
  raise exception 'Incomplete ${label} scored bank or ${priorLabel} prerequisite';
 end if;
 if exists(select 1 from literacy_mock_incoming incoming join public.literacy_mock_items old
  on old.id=incoming.item->>'id' and old.content_version='${manifest.contentVersion}'
  where old.item is distinct from incoming.item) then raise exception 'Cannot rewrite immutable ${label} publication'; end if;
 if exists(select 1 from public.literacy_mock_publications where content_version='${manifest.contentVersion}' and item_count<>${manifest.itemCount}) then
  raise exception 'Published mock catalogue count is immutable';
 end if;
end; $$;
insert into public.literacy_mock_items(id,content_version,item)
select item->>'id','${manifest.contentVersion}',item from literacy_mock_incoming on conflict(id,content_version) do nothing;
insert into public.literacy_mock_publications(content_version,item_count)
values('${manifest.contentVersion}',${manifest.itemCount}) on conflict(content_version) do nothing;
do $$begin
 if (select count(*) from public.literacy_mock_items where content_version='${manifest.contentVersion}')<>${manifest.itemCount}
  then raise exception 'Incomplete ${label} publication'; end if;
end; $$;
notify pgrst,'reload schema';
commit;
`;
}
