import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import sharp from 'sharp';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const args=process.argv.slice(2);
if(args.length>1 || (args[0] && !['--check','--write'].includes(args[0])))throw Error('Usage: node tools/buildClosingCartoonImages.mjs [--check|--write]');
const write=args[0]==='--write';
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const readJson=async file=>JSON.parse(await fs.readFile(path.join(root,file),'utf8'));
const general=await readJson('source-art/app-clean-cartoon/closing-images/manifest.json');
const rally=await readJson('source-art/arcade/physical-worlds/rally-pals/clean-cartoon-manifest.json');
const seen=new Set();
for(const asset of [...general.assets,...rally.assets]){
  if(seen.has(asset.path))throw Error('Duplicate delivery '+asset.path);
  seen.add(asset.path);
  const source=await fs.readFile(path.join(root,asset.nativeSaved));
  if(hash(source)!==asset.nativeSha256)throw Error('Changed native '+asset.jobId);
  if(hash(await fs.readFile(path.join(root,asset.promptFile)))!==asset.promptSha256)throw Error('Changed prompt '+asset.jobId);
  const output=await sharp(source).resize(asset.resize).webp(asset.encoding).toBuffer();
  if(hash(output)!==asset.outputSha256)throw Error('Non-reproducible encoding '+asset.jobId);
  const target=path.join(root,'public',asset.path.replace(/^\//,''));
  if(write)await fs.writeFile(target,output);
  if(hash(await fs.readFile(target))!==asset.outputSha256)throw Error('Changed canonical delivery '+asset.jobId);
}
const worlds={};
for(const world of ['meadow','dino','moonwood']){
  const atlas=rally.assets.find(a=>a.path.endsWith('/'+world+'-scenery-v1.webp'));
  const horizon=rally.assets.find(a=>a.path.endsWith('/'+world+'-horizon-v1.webp'));
  if(!atlas || !horizon || Object.keys(atlas.frames).length!==4 || !Number.isInteger(horizon.horizonFoot))throw Error('Incomplete Rally world '+world);
  for(const frame of Object.values(atlas.frames)){
    const [x,y,w,h]=frame;
    if(frame.length!==4 || frame.some(n=>!Number.isInteger(n)) || x<0||y<0||w<1||h<1||x+w>atlas.width||y+h>atlas.height)throw Error('Invalid whole-prop frame '+world);
  }
  worlds[world]={width:atlas.width,height:atlas.height,scenery:atlas.path,horizon:horizon.path,
    horizonWidth:horizon.width,horizonHeight:horizon.height,horizonFoot:horizon.horizonFoot,frames:atlas.frames};
}
const generated='// Measured whole-prop bounds and exact current runtime paths.\n// Generated by tools/buildClosingCartoonImages.mjs from the current Rally source manifest.\nexport const RALLY_PALS_WORLD_ART = Object.freeze('+JSON.stringify(worlds,null,2)+');\n';
const generatedPath=path.join(root,'src/data/generated/rallyPalsArt.generated.js');
if(write)await fs.writeFile(generatedPath,generated);
if(await fs.readFile(generatedPath,'utf8')!==generated)throw Error('Stale Rally registration');
console.log(`${write?'Rebuilt':'Verified'} ${seen.size} closing cartoon images and three measured Rally registrations.`);
