export async function literacyMockV9CatalogueSql() {
  const previous = await createLiteracyMockManifest({ contentVersion: 'literacy-mock-v8' });
  const manifest = await createLiteracyMockManifest({ contentVersion: 'literacy-mock-v9' });
  const byId = new Map(previous.items.map(item => [item.id, item]));
  const additions = manifest.items.filter(item => !byId.has(item.id));
  if (byId.size + additions.length !== manifest.itemCount || previous.items.some(old => !manifest.items.some(item => item.id === old.id))) throw Error('V9 must preserve every earlier identity.');
  const routeKeys = new Set(['contentVersion','adaptiveAreaVersion','adaptiveAreaBand','adaptiveMixedEligible','adaptiveDemand']);
  const patches = {}, bands = {};
  for (const item of manifest.items) {
    if (item.itemSnapshot.adaptiveMixedEligible) bands[item.id] = item.itemSnapshot.adaptiveAreaBand;
    const old = byId.get(item.id);
    if (!old) continue;
    if (Object.keys(old.itemSnapshot).some(key => !Object.hasOwn(item.itemSnapshot, key))) throw Error(`V9 removed a historical snapshot property: ${item.id}`);
    const patch = Object.fromEntries(Object.entries(item.itemSnapshot).filter(([key, value]) => !routeKeys.has(key) && JSON.stringify(old.itemSnapshot[key]) !== JSON.stringify(value)));
    if (Object.keys(patch).length) patches[item.id] = patch;
    for (const key of Object.keys(old).filter(key => key !== 'itemSnapshot')) if (JSON.stringify(old[key]) !== JSON.stringify(item[key])) throw Error(`Changed existing item needs a new V9 identity: ${item.id} ${key}`);
  }
  return `-- Generated by tools/generateLiteracyMockV9.mjs. New canonical publication; do not rewrite V1-V8.
begin;
create temporary table literacy_mock_incoming(item jsonb not null) on commit drop;
${compactIncomingSql(additions)}
with source as (select item,item->'itemSnapshot' s from public.literacy_mock_items where content_version='literacy-mock-v8'),
route as (select ${literal(bands)} bands,${literal(patches)} patches,${literal(LITERACY_MOCK_V9_LADDERS)} ladders),
classified as (select source.*,case when bands?(s->>'id') then (bands->>(s->>'id'))::integer else null end band,patches,ladders from source cross join route),
snapshots as (select item,s||coalesce(patches->(s->>'id'),'{}'::jsonb)||jsonb_build_object('contentVersion','literacy-mock-v9','adaptiveAreaVersion','areas-v5','adaptiveAreaBand',band,'adaptiveMixedEligible',band is not null,'adaptiveDemand',case when band is null then 'null'::jsonb else ladders->(s->>'domainId')->band end) snapshot from classified)
insert into literacy_mock_incoming select jsonb_set(item,'{itemSnapshot}',snapshot) from snapshots;
do $$begin
 if (select count(*) from public.literacy_mock_items where content_version='literacy-mock-v8')<>${previous.itemCount} or (select count(*) from literacy_mock_incoming)<>${manifest.itemCount} then raise exception 'Incomplete V9 publication'; end if;
 if exists(select 1 from literacy_mock_incoming incoming join public.literacy_mock_items old on old.id=incoming.item->>'id' and old.content_version='literacy-mock-v9' where old.item is distinct from incoming.item) then raise exception 'Cannot rewrite immutable V9 publication'; end if;
end; $$;
insert into public.literacy_mock_items(id,content_version,item) select item->>'id','literacy-mock-v9',item from literacy_mock_incoming on conflict(id,content_version) do nothing;
insert into public.literacy_mock_publications(content_version,item_count) values('literacy-mock-v9',${manifest.itemCount}) on conflict(content_version) do nothing;
do $$begin
 if (select count(*) from public.literacy_mock_items where content_version='literacy-mock-v9')<>${manifest.itemCount} or not exists(select 1 from public.literacy_mock_publications where content_version='literacy-mock-v9' and item_count=${manifest.itemCount}) then raise exception 'V9 publication count mismatch'; end if;
end; $$;
commit;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outputs = [[V9_SCHEMA_MIGRATION, literacyMockV9SchemaSql()]];
  if (!process.argv.includes('--schema-only')) outputs.push([V9_CATALOGUE_MIGRATION, await literacyMockV9CatalogueSql()]);
  for (const [name, sql] of outputs) {
    const path = new URL(`supabase/migrations/${name}`, root);
    if (process.argv.includes('--check')) { if (fs.readFileSync(path, 'utf8') !== sql) throw Error(`Stale generated V9 migration ${name}`); }
    else fs.writeFileSync(path, sql);
  }
  console.log('V9 schema/publication sources match.');
}
