const literal = value => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
const definitions = source => new Map([...source.matchAll(/create or replace function public\.(\w+)\([\s\S]*?\$\$;/g)].map(match => [match[1], match[0]]));
const expand = source => source.replaceAll("'literacy-mock-v8')", "'literacy-mock-v8','literacy-mock-v9')");
function replaceOnce(source, before, after) {
  if (source.split(before).length !== 2) throw Error(`Frozen V8 definition no longer matches V9 patch: ${before.slice(0, 100)}`);
  return source.replace(before, after);
}

