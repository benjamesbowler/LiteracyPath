import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { LITERACY_MOCK_AREA_ORDER } from '../src/policy/literacyMockAdaptivePolicy.js';
import { LITERACY_MOCK_V11_AREA_BUDGETS, LITERACY_MOCK_V11_MAX_ITEMS } from '../src/policy/literacyMockProgressionV11.js';
import { LITERACY_MOCK_SHORT_ITEM_COUNTS } from '../src/policy/literacyMockQuestionLimit.js';

export const V13_SCHEMA_MIGRATION = '20261122090000_literacy_mock_short_routing_v13.sql';
const migrations = new URL('../supabase/migrations/', import.meta.url);
const older = fs.readFileSync(new URL('20261028040100_literacy_mock_beginner_v12.sql', migrations), 'utf8');
const limits = fs.readFileSync(new URL('20261106055449_literacy_mock_question_limits.sql', migrations), 'utf8');
const definitions = new Map([...older.matchAll(/create or replace function public\.(\w+)\([\s\S]*?\$\$;/g),
  ...limits.matchAll(/create or replace function public\.(\w+)\([\s\S]*?\$\$;/g)]
  .map(([definition, name]) => [name, definition]));
const extend = definition => definition.replace(/\bin\s*\(([^()]*'literacy-mock-v12'[^()]*)\)/gi,
  (whole, values) => whole.replace(values, `${values},'literacy-mock-v13'`));
const replace = (source, from, to) => {
  assert.ok(source.includes(from), `Missing frozen SQL anchor: ${from}`);
  return source.replace(from, to);
};

function definitionWithGrants(definition, name) {
  const args = definition.match(/function public\.\w+\(([\s\S]*?)\)\s*returns/)[1];
  const types = args.split(',').map(value => value.trim()).filter(Boolean)
    .map(value => value.replace(/\s+default\b[\s\S]*/i, '').replace(/^\w+\s+/, '').trim());
  const signature = `public.${name}(${types.join(',')})`;
  const roles = name.startsWith('student_') ? 'anon,authenticated' : name.startsWith('teacher_') ? 'authenticated' : null;
  return `${definition}
revoke all on function ${signature} from public,anon,authenticated;${roles ? `\ngrant execute on function ${signature} to ${roles};` : ''}`;
}

export function literacyMockV13SchemaSql() {
  const parts = ['-- Generated by tools/generateLiteracyMockV13Schema.mjs. V13 adds balanced short routes and preserves prior schedules.\nbegin;'];
  // The later short-limit migration already owns the count and response
  // constraints. Extend only constraints whose content-version lists change.
  parts.push(extend(older.slice(older.indexOf('alter table'), older.indexOf('alter table public.literacy_mock_sessions')).trim()));
  parts.push(definitionWithGrants(`create or replace function public.teacher_literacy_mock_v13_available()
returns boolean language plpgsql stable security definer set search_path='' as $$
begin
 perform public.assert_current_actor_teacher_access();
 return to_regprocedure('public.teacher_get_literacy_mock_status(uuid)') is not null
  and exists (select 1 from public.literacy_mock_publications p
   where p.content_version='literacy-mock-v13' and p.available_for_new_sessions
    and p.item_count=(select count(*) from public.literacy_mock_items i where i.content_version=p.content_version)
    and (select count(distinct i.item->>'domainId') from public.literacy_mock_items i where i.content_version=p.content_version)=${LITERACY_MOCK_AREA_ORDER.length});
end; $$;`, 'teacher_literacy_mock_v13_available'));
  parts.push(definitionWithGrants(`create or replace function public.lp_mock_balanced_schedule_v13(p_rows jsonb,p_states jsonb,p_session_id uuid)
returns jsonb language plpgsql immutable set search_path='' as $$
declare
 v_budgets jsonb:='${JSON.stringify(LITERACY_MOCK_V11_AREA_BUDGETS)}'::jsonb;
 v_order text[]:=array[${LITERACY_MOCK_AREA_ORDER.map(area => `'${area}'`).join(',')}];
 v_schedule jsonb:='[]'; v_row jsonb; v_domain text; v_ordinal integer; v_area integer;
 v_shift integer:=mod(strpos('0123456789abcdef',right(p_session_id::text,1))-1,${LITERACY_MOCK_AREA_ORDER.length});
begin
 for v_row in select value from jsonb_array_elements(coalesce(p_rows,'[]')) loop
  if v_row->>'responseStatus'='media_failed' then continue; end if;
  v_domain:=coalesce(v_row#>>'{itemSnapshot,domainId}',v_row#>>'{questionSnapshot,domainId}',v_row->>'domainId');
  if v_domain is null or not v_budgets ? v_domain then raise exception 'Invalid adaptive boundary history'; end if;
  v_schedule:=v_schedule||jsonb_build_array(v_domain);
 end loop;
 foreach v_domain in array v_order loop
  if (p_states#>>array[v_domain,'answered'])::integer>(v_budgets->>v_domain)::integer then raise exception 'Invalid adaptive boundary history'; end if;
 end loop;
 if jsonb_array_length(v_schedule)>${LITERACY_MOCK_V11_MAX_ITEMS} then raise exception 'Invalid adaptive boundary history'; end if;
 for v_ordinal in 1..${Math.max(...Object.values(LITERACY_MOCK_V11_AREA_BUDGETS))} loop
  for v_area in 0..${LITERACY_MOCK_AREA_ORDER.length - 1} loop
   v_domain:=v_order[1+mod(v_area+coalesce(v_shift,0),${LITERACY_MOCK_AREA_ORDER.length})];
   if v_ordinal<=(v_budgets->>v_domain)::integer and v_ordinal>(p_states#>>array[v_domain,'answered'])::integer
     and not (p_states#>>array[v_domain,'complete'])::boolean then v_schedule:=v_schedule||jsonb_build_array(v_domain); end if;
  end loop;
 end loop;
 return v_schedule;
end; $$;`, 'lp_mock_balanced_schedule_v13'));

  for (const [name, source] of definitions) {
    if (name === 'lp_mock_session_boundary_schedule') {
      const schedule = replace(source, 'public.lp_mock_boundary_schedule_for_version(p_rows,p_states,p_version)',
        `case when p_version='literacy-mock-v13' then public.lp_mock_balanced_schedule_v13(p_rows,p_states,p_session_id)
   else public.lp_mock_boundary_schedule_for_version(p_rows,p_states,p_version) end`);
      parts.push(definitionWithGrants(schedule, name));
      continue;
    }
    if (!source.includes('literacy-mock-v12') && name !== 'teacher_prepare_literacy_mock_session_v12') continue;
    if (['lp_mock_prepare_v12_before_delivery','teacher_prepare_literacy_mock_session_v12'].includes(name)) {
      let preparation = source.replaceAll('v12', 'v13').replace('p_item_count integer default 124', 'p_item_count integer default 25');
      if (name === 'lp_mock_prepare_v12_before_delivery') {
        preparation = replace(preparation, 'p_item_count not in (15,25,40,124)', `p_item_count not in (${LITERACY_MOCK_SHORT_ITEM_COUNTS.join(',')})`);
        const publicationGuard = preparation.match(/if not exists\(select 1 from public\.literacy_mock_publications[\s\S]*?=8\) then/)[0];
        preparation = replace(preparation, publicationGuard, 'if not public.teacher_literacy_mock_v13_available() then');
      }
      parts.push(definitionWithGrants(preparation, name.replace('v12', 'v13')));
      continue;
    }
    let definition = extend(source);
    if (name === 'lp_literacy_mock_state') {
      definition = replace(definition, "jsonb_build_object('offlineDelivery',", `jsonb_build_object(
   'preRenderMediaFailure',v_mock->>'content_version'='literacy-mock-v13',
   'offlineDelivery',`);
    }
    if (name === 'student_save_literacy_mock_run') {
      definition = replace(definition, "if v_presentation is null then return json_build_object('ok',false,'error','presentation_required'); end if;",
        `-- A V13 device may document required media that failed before the question was shown.
      if v_presentation is null and not (v_version='literacy-mock-v13' and p_response->>'responseStatus'='media_failed')
       then return json_build_object('ok',false,'error','presentation_required'); end if;`);
      definition = replace(definition, "then v_presentation->'familiarityReasons' else",
        "then coalesce(v_presentation->'familiarityReasons','[]'::jsonb) else");
    }
    parts.push(definitionWithGrants(definition, name));
  }
  parts.push("notify pgrst,'reload schema';\ncommit;\n");
  return parts.join('\n\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL(V13_SCHEMA_MIGRATION, migrations);
  if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8'), literacyMockV13SchemaSql());
  else fs.writeFileSync(target, literacyMockV13SchemaSql());
}
