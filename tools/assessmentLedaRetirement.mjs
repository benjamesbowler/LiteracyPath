import { createHash } from 'node:crypto';
import { normalizeLedaAudioText } from '../src/data/ledaProductionAudio.js';

const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const roles = new Set(['assessment_prompt', 'assessment_passage', 'isolated_word']);

/** Parse the exact reviewed bytes, avoiding a stale Node import during a merge. */
export function parseAssessmentLedaMapSource(bytes) {
  const match = String(bytes).match(/export const ASSESSMENT_LEDA_GAP_AUDIO_BY_ROLE = Object\.freeze\((\{[\s\S]*\})\);\s*$/);
  if (!match) throw new Error('Unsupported generated audio map format.');
  return JSON.parse(match[1]);
}

/** Validate an exact local retirement before changing a map or moving any bytes. */
export async function prepareAssessmentLedaRetirement(worklist, {
  map, mapBytes, readAudio, references,
}) {
  if (worklist?.scope !== 'assessment-leda-exact-retirement'
    || !/^[a-f0-9]{64}$/.test(worklist.expectedMapSha256 || '')
    || !Array.isArray(worklist.records) || !worklist.records.length
    || !Array.isArray(references)) throw new Error('Invalid exact audio retirement worklist or reference inventory.');
  if (digest(mapBytes) !== worklist.expectedMapSha256) throw new Error('Audio map changed since retirement review.');
  const nextMap = structuredClone(map);
  const seen = new Set();
  const records = [];
  for (const row of worklist.records) {
    if (!roles.has(row.role) || typeof row.key !== 'string' || !row.key
      || normalizeLedaAudioText(row.key) !== row.key
      || !new RegExp(`^/audio/production/en-US/${row.role}/[a-z0-9-]+\\.mp3$`).test(row.publicPath || '')
      || !/^[a-f0-9]{64}$/.test(row.sha256 || '')
      || typeof row.reason !== 'string' || !row.reason.trim()) throw new Error('Invalid exact audio retirement record.');
    const identity = `${row.role}|${row.key}`;
    if (seen.has(identity)) throw new Error(`Repeated audio retirement: ${identity}`);
    seen.add(identity);
    if (map[row.role]?.[row.key] !== row.publicPath) throw new Error(`Audio retirement mapping changed: ${identity}`);
    const shared = Object.entries(map).flatMap(([role, values]) => Object.entries(values)
      .filter(([key, value]) => value === row.publicPath && (role !== row.role || key !== row.key))
      .map(([key]) => `${role}|${key}`));
    if (shared.length) throw new Error(`Audio retirement has another map owner: ${shared.join(', ')}`);
    const used = references.filter(reference => reference.path?.split(/[?#]/)[0] === row.publicPath);
    if (used.length) throw new Error(`Audio retirement still referenced: ${identity}: ${used.map(reference => reference.source).join(', ')}`);
    const bytes = await readAudio(row.publicPath);
    if (digest(bytes) !== row.sha256) throw new Error(`Audio retirement bytes changed: ${identity}`);
    records.push({ ...row, bytes });
    delete nextMap[row.role][row.key];
  }
  return { nextMap, records };
}

export function assessmentLedaMapSource(map, voice) {
  return [
    '// AUTO-GENERATED by tools/generateAssessmentLedaGaps.mjs. Do not edit.',
    `export const ASSESSMENT_LEDA_GAP_VOICE = ${JSON.stringify(voice)};`,
    `export const ASSESSMENT_LEDA_GAP_AUDIO_BY_ROLE = Object.freeze(${JSON.stringify(map, null, 2)});`,
    '',
  ].join('\n');
}
