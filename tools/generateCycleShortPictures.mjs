import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import sharp from 'sharp';
import { CYCLE_SHORTS } from '../src/content/cycle-shorts/passages.js';
import { cycleShortPicturePrompt, CYCLE_SHORT_SCENES } from './authoring/cycleShortPictures.mjs';
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const manifestPath = 'docs/content/cycle-short-images/provenance.json';
const modulePath = 'src/content/cycle-shorts/pictures.generated.js';
const referencePath = '/images/worksheets/muddy-colouring.webp';
const referenceSha256 = sha(await readFile(`public${referencePath}`));
let entries;
if (process.argv.includes('--check')) {
  entries = JSON.parse(await readFile(manifestPath,'utf8'));
} else {
  const sources = JSON.parse(await readFile(process.argv[2],'utf8'));
  await mkdir('public/images/comprehension/cycle-shorts',{recursive:true});
  await mkdir('docs/content/cycle-short-images',{recursive:true});
  entries = {};
  for (const p of CYCLE_SHORTS.filter(p=>!p.sourcePassageId)) {
    const source = await readFile(sources[p.cycleNumber]);
    const src = `/images/comprehension/cycle-shorts/${p.id}.webp`;
    await sharp(source).resize({width:1800,withoutEnlargement:true}).webp({quality:85}).toFile(`public${src}`);
    entries[p.id] = {src,sourceSha256:sha(source),assetSha256:sha(await readFile(`public${src}`)),sourceText:p.text,prompt:cycleShortPicturePrompt(p),referencePath,referenceSha256,generator:'Built-in image_gen',generatedAt:'2026-11-03',visualReview:null};
  }
  await writeFile(manifestPath,JSON.stringify(entries,null,2)+'\n');
}
const pictures = {};
for (const p of CYCLE_SHORTS.filter(p=>!p.sourcePassageId)) {
  const entry = entries[p.id];
  if (!entry || entry.sourceText!==p.text || entry.prompt!==cycleShortPicturePrompt(p) || entry.referenceSha256!==referenceSha256) throw new Error(`${p.id}: stale provenance`);
  const bytes = await readFile(`public${entry.src}`);
  const metadata = await sharp(bytes).metadata();
  if (entry.assetSha256!==sha(bytes) || metadata.width<1200 || metadata.height<350) throw new Error(`${p.id}: invalid image`);
  await sharp(bytes).raw().toBuffer();
  pictures[p.id] = {src:entry.src,sourceText:p.text,alt:CYCLE_SHORT_SCENES[p.cycleNumber].map((text,i)=>`${['First','Next','Last'][i]}: ${text}`).join(' ')};
  if (process.argv.includes('--check') && !entry.visualReview) throw new Error(`${p.id}: inspect the actual picture before acceptance`);
}
const output = '// Generated by tools/generateCycleShortPictures.mjs; edit authoring source instead.\nexport const CYCLE_SHORT_PICTURES = '+JSON.stringify(pictures,null,2)+';\n';
if (process.argv.includes('--check')) {
  if(await readFile(modulePath,'utf8')!==output) throw new Error('Stale Cycle Shorts picture module');
} else await writeFile(modulePath,output);
console.log(`Cycle Shorts pictures: ${Object.keys(pictures).length} story-specific comics decoded and verified.`);
