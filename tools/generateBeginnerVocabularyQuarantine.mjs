import fs from 'node:fs';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { loadLiteracyMockBank } from '../src/data/literacyMockBank.js';
import { literacyMockBeginnerVocabularyIssue } from '../src/policy/literacyMockBeginnerVocabulary.js';

export const BEGINNER_VOCABULARY_MIGRATION = '20261028040000_literacy_mock_beginner_vocabulary.sql';
const root = new URL('../', import.meta.url);
const quote = value => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;

// Forward selection quarantine. Catalogue rows, answers, keys and saved
// snapshots are never edited. Match the canonical published version and demand.
export async function beginnerVocabularyQuarantineSql() {
  const index = {};
  for (let version = 4; version <= 12; version++) {
    const contentVersion = `literacy-mock-v${version}`;
    const bank = await loadLiteracyMockBank({ contentVersion, includeUnavailable: true });
    for (const item of bank) {
      const issue = literacyMockBeginnerVocabularyIssue(item.itemSnapshot);
      if (issue) index[`${contentVersion}:${item.id}`] = {
        areaVersion: item.adaptiveAreaVersion, band: item.adaptiveAreaBand, issue,
      };
    }
  }
  const previous = fs.readFileSync(new URL('supabase/migrations/20261016202515_literacy_mock_v10_quality_lookup.sql', root), 'utf8');
  const original = previous.match(/create or replace function public\.lp_literacy_item_quality_issue\([\s\S]*?\$\$;/)?.[0];
  assert.ok(original, 'The existing applied quality lookup must be preserved.');
  return `-- Generated by tools/generateBeginnerVocabularyQuarantine.mjs.
-- Selection/reporting quarantine only; immutable publications stay unchanged.
begin;
${original.replace('public.lp_literacy_item_quality_issue(', 'public.lp_literacy_quality_before_beginner_words(')}
revoke all on function public.lp_literacy_quality_before_beginner_words(jsonb) from public,anon,authenticated;
create or replace function public.lp_literacy_item_quality_issue(p_value jsonb)
returns jsonb language sql immutable set search_path='' as $$
 with source as materialized (
  select coalesce(nullif(p_value->'itemSnapshot','null'::jsonb),nullif(p_value->'questionSnapshot','null'::jsonb),nullif(p_value->'question','null'::jsonb),p_value) s
 ), reviewed as (
  select s,${quote(index)}->((s->>'contentVersion')||':'||(s->>'id')) rule from source
 )
 select coalesce(public.lp_literacy_quality_before_beginner_words(p_value),
  case when s->>'adaptiveAreaVersion'=rule->>'areaVersion' and s->'adaptiveAreaBand'=rule->'band'
   then rule->'issue' end) from reviewed;
$$;
revoke all on function public.lp_literacy_item_quality_issue(jsonb) from public,anon,authenticated;
notify pgrst,'reload schema';
commit;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sql = await beginnerVocabularyQuarantineSql();
  const target = new URL(`supabase/migrations/${BEGINNER_VOCABULARY_MIGRATION}`, root);
  if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8'), sql);
  else fs.writeFileSync(target, sql);
  console.log(`Beginner vocabulary quarantine: ${Buffer.byteLength(sql)} bytes; no hosted changes.`);
}
