import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import sharp from "sharp";

import { bookCoverSources } from "../src/policy/childLibraryPolicy.js";
import { GUIDED_READING_COVER_RENDITIONS, GUIDED_READING_COVER_ENCODING } from "../src/data/generated/guidedReadingCoverRenditions.generated.js";
import worldDiscoveryCohorts from "../src/content/world-discovery/cohorts.json" with { type: "json" };
import { readWorldDiscoveryCohort } from "./worldDiscoveryCohortReleaseLib.mjs";

// Card delivery only: keep the canonical source art and full reader images.
// A full gallery decoding original multi-megapixel covers in the same frame
// can exhaust Chromium's decoded-image budget even when every file is valid.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const maxEdge = 512;
const encoding = { format: "webp", quality: 92, effort: 6, maxEdge };
const digest = bytes => createHash("sha256").update(bytes).digest("hex");
const args = process.argv.slice(2);
if (args.length && (args.length !== 2 || args[0] !== "--world-discovery-cohort")) throw Error("Usage: buildGuidedReadingCoverRenditions.mjs [--world-discovery-cohort ID]");
const cohort = args.length ? worldDiscoveryCohorts.cohorts.find(row => row.id === args[1] && row.index > 0) : null;
if (args.length && !cohort) throw Error("Select a declared expansion cohort; original card evidence is immutable");
const selectedSources = cohort ? readWorldDiscoveryCohort(cohort).books.map(book => `/guided-reading/world-discovery/${book.id.replace("world-discovery-", "")}/cover.webp`)
  : (await import("../src/utils/guidedReading/runtimeBooks.js")).getRuntimeGuidedReadingBooks().map(book => bookCoverSources(book)[0]).filter(Boolean);
const sources = [...new Set(selectedSources)].sort();
const outputDirectory = path.join(root, "public/guided-reading/card-covers");
await fs.mkdir(outputDirectory, { recursive: true });
const entries = [];
for (const source of sources) {
  const sourceBytes = await fs.readFile(path.join(root, "public", source));
  const previous = GUIDED_READING_COVER_RENDITIONS[source];
  if (previous?.sourceSha256 === digest(sourceBytes) && Object.entries(encoding).every(([key, value]) => GUIDED_READING_COVER_ENCODING[key] === value)) {
    const previousBytes = await fs.readFile(path.join(root, "public", previous.src)).catch(() => null);
    if (previousBytes && digest(previousBytes) === previous.deliverySha256) {
      entries.push([source, previous]);
      continue;
    }
  }
  const sourceMetadata = await sharp(sourceBytes).metadata();
  const { data, info } = await sharp(sourceBytes)
    .resize({ width: maxEdge, height: maxEdge, fit: "inside", withoutEnlargement: true })
    .webp({ quality: encoding.quality, effort: encoding.effort })
    .toBuffer({ resolveWithObject: true });
  const deliverySha256 = digest(data);
  const src = `/guided-reading/card-covers/${deliverySha256.slice(0, 24)}.webp`;
  await fs.writeFile(path.join(root, "public", src), data);
  entries.push([source, {
    src, sourceSha256: digest(sourceBytes), deliverySha256,
    sourceWidth: sourceMetadata.width, sourceHeight: sourceMetadata.height,
    width: info.width, height: info.height, bytes: info.size
  }]);
}
if (cohort) {
  const file = path.join(root, `.artifacts/world-discovery-expansion/cards/${cohort.id}-renditions.json`);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, JSON.stringify({ cohortId: cohort.id, status: "generated-awaiting-direct-review", encoding, entries: Object.fromEntries(entries) }, null, 2) + "\n");
  console.log(`Prepared isolated card delivery metadata: ${path.relative(root, file)}. No runtime manifest or visual approval changed.`);
} else {
  const rows = entries.map(([source, entry]) => `  ${JSON.stringify(source)}: Object.freeze(${JSON.stringify(entry)})`).join(",\n");
  await fs.writeFile(path.join(root, "src/data/generated/guidedReadingCoverRenditions.generated.js"),
    `// Generated by node tools/buildGuidedReadingCoverRenditions.mjs. Do not edit.\n// Exact canonical artwork; card delivery only. Original reader assets are retained.\nexport const GUIDED_READING_COVER_ENCODING = Object.freeze(${JSON.stringify(encoding)});\nexport const GUIDED_READING_COVER_RENDITIONS = Object.freeze({\n${rows}\n});\n`);
}
console.log(`Built ${entries.length} card renditions from retained canonical covers (${entries.reduce((sum, [, entry]) => sum + entry.bytes, 0)} bytes).`);
