import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { LITERACY_QUARANTINED_ITEM_IDS, LITERACY_CONTEXTUAL_ITEM_QUALITY_ISSUES, literacyItemQualityIssue } from '../src/policy/literacyItemEligibility.js';

export const V10_QUALITY_LOOKUP_MIGRATION = '20261016202515_literacy_mock_v10_quality_lookup.sql';
const root = new URL('../', import.meta.url);
const appliedSchema = new URL('supabase/migrations/20261016184804_literacy_mock_boundary_v10.sql', root);
const appliedSha = 'c4c2f1d5d5676f39554aa1202095dc6029e3f4a2e1ddf1cd628beba1633b5e17';
const sqlText = value => `'${String(value).replaceAll("'", "''")}'`;

/** Forward-only lookup optimization. Original row ordinals preserve the
 * applied SQL's priority even when different aliases name different issues. */
export function literacyMockV10QualityLookupSql() {
  const applied = fs.readFileSync(appliedSchema, 'utf8');
  assert.equal(crypto.createHash('sha256').update(applied).digest('hex'), appliedSha, 'The applied V10 schema changed.');
  const rows = [
    ...LITERACY_QUARANTINED_ITEM_IDS.map(id => ({ id, issue: literacyItemQualityIssue({ id }), context: null })),
    ...LITERACY_CONTEXTUAL_ITEM_QUALITY_ISSUES.map(({ id, issue, ...context }) => ({ id, issue, context })),
  ];
  const index = Object.create(null);
  rows.forEach(({ id, issue, context }, priority) => {
    (index[id] ||= []).push({ priority, issue, context });
  });
  return `-- Generated by tools/generateLiteracyMockV10QualityLookup.mjs.
-- Forward-only: only the existing private immutable quality lookup changes.
-- Source is expanded once; inspect rules for at most five matching IDs.
-- Original authority ordinals preserve global/context and alias priority.
begin;
create or replace function public.lp_literacy_item_quality_issue(p_value jsonb)
returns jsonb language sql immutable set search_path='' as $$
 with source as materialized (
  select coalesce(nullif(p_value->'itemSnapshot','null'::jsonb),nullif(p_value->'questionSnapshot','null'::jsonb),nullif(p_value->'question','null'::jsonb),p_value) s
 ), candidates as materialized (
  select s,rule from source
  cross join lateral (select distinct id from unnest(array[p_value->>'questionId',p_value->>'id',s->>'id',p_value->>'sourceItemId',s->>'sourceItemId']) ids(id)
   where id is not null) candidate
  cross join lateral jsonb_array_elements(${sqlText(JSON.stringify(index))}::jsonb->candidate.id) rules(rule)
 )
 select rule->'issue' from candidates
 where rule->'context'='null'::jsonb or (
  s->>'adaptiveAreaVersion'=rule->'context'->>'adaptiveAreaVersion'
  and s->'adaptiveAreaBand'=rule->'context'->'adaptiveAreaBand'
  and (not (rule->'context' ? 'contentVersion') or s->>'contentVersion'=rule->'context'->>'contentVersion'))
 order by (rule->>'priority')::integer
 limit 1;
$$;
revoke all on function public.lp_literacy_item_quality_issue(jsonb) from public,anon,authenticated;
notify pgrst, 'reload schema';
commit;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sql = literacyMockV10QualityLookupSql(), target = new URL(`supabase/migrations/${V10_QUALITY_LOOKUP_MIGRATION}`, root);
  if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8'), sql, 'Stale V10 quality lookup migration.');
  else fs.writeFileSync(target, sql);
  console.log('V10 quality lookup migration matches its source.');
}
