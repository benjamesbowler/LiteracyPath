import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {loadLiteracyMockBank, literacyMockTutorialIdsForVersion} from '../src/data/literacyMockBank.js';
import {PROGRESS_CHECK_INSTRUCTIONS} from '../src/data/progressCheckInstructions.js';
import {progressCheckAudioPath} from '../src/utils/progressCheckAudio.js';

async function versionSources(version='literacy-mock-v10') {
  const bank=await loadLiteracyMockBank({contentVersion:version,includeUnavailable:true});
  const items=bank.filter(item=>item.tutorialOnly || item.adaptiveMixedEligible);
  if(Object.values(literacyMockTutorialIdsForVersion(version)).some(id=>!items.some(item=>item.id===id))) throw Error('Runtime tutorials are incomplete.');
  const snapshots=JSON.parse(JSON.stringify(items.map(item=>item.itemSnapshot)));
  const dictionary=[],identities=new Map(),layouts=[],layoutIds=new Map();
  const atom=value=>{const key=JSON.stringify(value);if(!identities.has(key)){identities.set(key,dictionary.length);dictionary.push(value);}return identities.get(key);};
  const pack=value=>{
    if(Array.isArray(value))return [0,...value.map(pack)];
    if(value && typeof value==='object'){
      if(version==='literacy-mock-v11'){
        const keys=Object.keys(value),shape=JSON.stringify(keys);
        if(!layoutIds.has(shape)){layoutIds.set(shape,layouts.length);layouts.push(keys.map(atom));}
        return [2,layoutIds.get(shape),...Object.values(value).map(pack)];
      }
      return [1,...Object.entries(value).flatMap(([key,child])=>[atom(key),pack(child)])];
    }
    return atom(value);
  };
  const records=snapshots.map(pack),hash=createHash('sha256').update(JSON.stringify(snapshots)).digest('hex');
  const bankSource=`// Generated by tools/generateLiteracyMockRuntime.mjs. Exact published mixed ${version.replace('literacy-mock-','').toUpperCase()} snapshots.\n// Source SHA-256: ${hash}\nconst packed=${JSON.stringify(version==='literacy-mock-v11'?{dictionary,layouts,records}:{dictionary,records})};\nconst unpack=node=>typeof node==='number'?packed.dictionary[node]:node[0]===0?node.slice(1).map(unpack):${version==='literacy-mock-v11'?"node[0]===2?Object.fromEntries(packed.layouts[node[1]].map((key,i)=>[packed.dictionary[key],unpack(node[i+2])])):":""}Object.fromEntries(Array.from({length:(node.length-1)/2},(_,i)=>[packed.dictionary[node[i*2+1]],unpack(node[i*2+2])]));\nexport const LITERACY_MOCK_RUNTIME_${version.replace('literacy-mock-','').toUpperCase()}=packed.records.map(record=>{const snapshot=unpack(record);return {...snapshot,itemSnapshot:snapshot};});\n`;
  const audio=Object.fromEntries(['circle','readPassage'].map(key=>[key,progressCheckAudioPath(PROGRESS_CHECK_INSTRUCTIONS[key])]));
  if(Object.values(audio).some(path=>!path)) throw Error('Runtime instruction recording missing.');
  const audioSource=`// Generated by tools/generateLiteracyMockRuntime.mjs. Canonical recordings, no full audio catalogue download.\nexport const MOCK_RUNTIME_INSTRUCTION_AUDIO=Object.freeze(${JSON.stringify(audio,null,2)});\n`;
  return new Map([[`src/data/generated/literacyMockRuntime${version.replace('literacy-mock-','').toUpperCase()}.generated.js`,bankSource],['src/data/generated/literacyMockRuntimeAudio.generated.js',audioSource]]);
}

export async function literacyMockRuntimeSources() {
  return new Map([...(await versionSources()),...(await versionSources('literacy-mock-v11'))]);
}

if(process.argv[1] && new URL(`file://${process.argv[1]}`).href===import.meta.url) {
  for(const [path,source] of await literacyMockRuntimeSources()) {
    if(process.argv.includes('--check')) {if(fs.readFileSync(path,'utf8')!==source)throw Error(`${path} is stale.`);}
    else fs.writeFileSync(path,source);
    console.log(`${path}: ${Buffer.byteLength(source)} bytes.`);
  }
}
