#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { validateWorldDiscoveryCohortManifest } from "../src/data/worldDiscoveryCohortContract.js";
import { auditWorldDiscoveryCohort, addWorldDiscoveryApprovedAudio, buildWorldDiscoveryAudioPlan, readWorldDiscoveryCohort, validateWorldDiscoveryEvidenceReceipt } from "./worldDiscoveryCohortReleaseLib.mjs";
import { validateWorldDiscoveryCohortDrafts } from "./worldDiscoveryValidationLib.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = path.join(root, "src/content/world-discovery/cohorts.json");
const modulePath = path.join(root, "src/data/generated/worldDiscoveryCohorts.generated.js");
const readJson = file => JSON.parse(fs.readFileSync(path.resolve(root, file), "utf8"));
const writeJson = (file, value) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, JSON.stringify(value, null, 2) + "\n"); };

export function worldDiscoveryCohortModule(manifest) {
  const lines = ["// Generated by tools/registerWorldDiscoveryCohorts.mjs. Sources remain canonical; inactive cohorts have no imports."];
  const entries = [];
  for (const cohort of manifest.cohorts.filter(row => row.active)) {
    const prefix = `c${cohort.index}`;
    const importJson = (name, file) => lines.push(`import ${name} from ${JSON.stringify(path.posix.relative("src/data/generated", file))} with { type: "json" };`);
    for (const level of "abcde") importJson(prefix + level, `${cohort.sourceDir}/level-${level}.json`);
    importJson(prefix + "reviews", `${cohort.sourceDir}/reviews.json`);
    importJson(prefix + "registration", cohort.registration);
    entries.push(`  { id: ${JSON.stringify(cohort.id)}, books: [${[..."abcde"].map(level => `...${prefix}${level}`).join(", ")}], reviews: ${prefix}reviews, registration: ${prefix}registration }`);
  }
  lines.push(`export const WORLD_DISCOVERY_REGISTERED_COHORTS = Object.freeze([\n${entries.join(",\n")}\n]);`);
  return lines.join("\n") + "\n";
}

export async function checkRegisteredWorldDiscoveryCohorts({ manifest = readJson(manifestPath), complete = false, checkModule = true } = {}) {
  const failures = validateWorldDiscoveryCohortManifest(manifest);
  if (complete && manifest.cohorts.some(cohort => !cohort.active)) failures.push(`Expansion is incomplete: all ${manifest.targetBooks} declared books must be registered`);
  if (failures.length) throw Error(failures.join("\n"));
  if (checkModule && fs.readFileSync(modulePath, "utf8") !== worldDiscoveryCohortModule(manifest)) throw Error("Generated World Discovery imports are stale");
  const entries = [], priorAudio = new Map(), priorImages = new Set();
  for (const cohort of manifest.cohorts.filter(row => row.active)) {
    const audited = await auditWorldDiscoveryCohort(cohort, priorAudio);
    const receiptFailures = validateWorldDiscoveryEvidenceReceipt(readJson(cohort.registration), audited.registration);
    if (receiptFailures.length) throw Error(`${cohort.id}: ${receiptFailures.join("; ")}`);
    for (const digest of audited.imageDigests) {
      if (priorImages.has(digest)) throw Error(`${cohort.id}: canonical artwork repeats a registered cohort`);
      priorImages.add(digest);
    }
    entries.push({ ...audited, cohort });
    addWorldDiscoveryApprovedAudio(priorAudio, audited.audio);
  }
  const sourceFailures = validateWorldDiscoveryCohortDrafts(entries).failures;
  if (sourceFailures.length) throw Error(sourceFailures.join("\n"));
  return { manifest, entries, priorAudio, priorImages };
}

export async function registerWorldDiscoveryCohort(id, { write = false, audioPlan = false } = {}) {
  const manifest = readJson(manifestPath);
  const failures = validateWorldDiscoveryCohortManifest(manifest);
  if (failures.length) throw Error(failures.join("\n"));
  const cohort = manifest.cohorts.find(row => row.id === id);
  if (!cohort) throw Error(`Unknown declared World Discovery cohort: ${id}`);
  if (cohort.index === 0 && fs.existsSync(path.join(root, cohort.registration))) throw Error("Original cohort registration is immutable; use --check");
  if (cohort.index && cohort.active) throw Error("Cohort is already registered; use --check");
  if (manifest.cohorts.some(row => row.index < cohort.index && !row.active)) throw Error("Register cohorts in declared order");
  const previous = cohort.index ? await checkRegisteredWorldDiscoveryCohorts() : { priorAudio: new Map(), priorImages: new Set() };
  if (audioPlan) {
    if (!cohort.narrationInventory) throw Error("The original narration report is immutable");
    const inventory = buildWorldDiscoveryAudioPlan(cohort, readWorldDiscoveryCohort(cohort), previous.priorAudio);
    if (write) writeJson(path.join(root, cohort.narrationInventory), inventory);
    return { cohort: id, requiredScreening: inventory.required.length, reusedClips: inventory.reused.length, inventory: cohort.narrationInventory, written: write };
  }
  const audited = await auditWorldDiscoveryCohort(cohort, previous.priorAudio);
  const sourceFailures = validateWorldDiscoveryCohortDrafts([...(previous.entries || []), { ...audited, cohort }]).failures;
  if (sourceFailures.length) throw Error(sourceFailures.join("\n"));
  for (const digest of audited.imageDigests) if (previous.priorImages.has(digest)) throw Error(`${id}: canonical artwork repeats a registered cohort`);
  if (write) {
    writeJson(path.join(root, cohort.registration), audited.registration);
    cohort.active = true;
    fs.writeFileSync(modulePath, worldDiscoveryCohortModule(manifest));
    writeJson(manifestPath, manifest);
  }
  return { cohort: id, ...audited.registration.counts, written: write,
    next: "Run canonical level/index, narration provenance/clearance, cover and page-alignment registration, then all global release and browser gates before publishing." };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args[0] === "--check" && args.slice(1).every(arg => arg === "--complete")) {
    const { manifest, entries } = await checkRegisteredWorldDiscoveryCohorts({ complete: args.includes("--complete") });
    console.log(`World Discovery registration: ${entries.length}/${manifest.cohorts.length} cohorts; ${entries.reduce((count, entry) => count + entry.cohort.expectedBooks, 0)}/${manifest.targetBooks} declared books; current source/review/media hashes verified.`);
  } else if (["--register", "--audit", "--plan-audio"].includes(args[0]) && args[1] && args.length === 2) {
    console.log(JSON.stringify(await registerWorldDiscoveryCohort(args[1], { write: args[0] !== "--audit", audioPlan: args[0] === "--plan-audio" })));
  } else throw Error("Usage: registerWorldDiscoveryCohorts.mjs --check [--complete] | --audit ID | --plan-audio ID | --register ID");
}
