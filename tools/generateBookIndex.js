// Emits a tiny discovery index of all guided reading books so the
// daily mission (loaded on the student home screen) doesn't pull the full
// book data files into the main bundle. Runs via the npm "prebuild" script.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "src", "data", "generated", "guidedReadingBookIndex.generated.js");

const { getRuntimeGuidedReadingBooks } = await import(path.join(root, "src/utils/guidedReading/runtimeBooks.js"));
const { getGuidedReadingBookMetadata } = await import(path.join(root, "src/data/guidedReadingBookMetadata.js"));
const { GUIDED_READING_LEVEL_REVIEWS } = await import(path.join(root, "src/data/guidedReadingLevelReviews.js"));
const { GUIDED_READING_TEXT_ANALYSIS } = await import(path.join(root, "src/data/generated/guidedReadingTextAnalysis.generated.js"));
const { computeBookTextMetrics, fingerprintBookReadingText } = await import(path.join(root, "src/utils/guidedReading/textMetrics.js"));

// Retain the reviewed active page subset without importing full manuscripts on
// home/report screens. A retired illustration removes its page from the reader.
function reviewedPageMedia(book) {
  const paths = book.pages.map(page => page.image || "");
  let prefix = paths[0] || "";
  while (prefix && !paths.every(image => image.startsWith(prefix))) prefix = prefix.slice(0, -1);
  prefix = prefix.slice(0, prefix.lastIndexOf("/") + 1);
  return { prefix, pages: book.pages.map(page => [page.pageNumber, (page.image || "").slice(prefix.length)]) };
}

const index = getRuntimeGuidedReadingBooks().map(book => {
  const metadata = getGuidedReadingBookMetadata(book);
  const review = GUIDED_READING_LEVEL_REVIEWS[book.id];
  const textFingerprint = fingerprintBookReadingText(book);
  if (!review || review.reviewedTextFingerprint !== textFingerprint
    || !/^[A-H]$/.test(review.appReadingLevel || "")) {
    throw new Error(`${book.id}: current full-manuscript A-H review is required for public metadata.`);
  }
  const metrics = computeBookTextMetrics(book);
  const analysis = GUIDED_READING_TEXT_ANALYSIS[book.id];
  if (!analysis || analysis.textFingerprint !== textFingerprint
    || analysis.appReadingLevel !== review.appReadingLevel
    || analysis.rationale !== review.rationale
    || analysis.reviewedAt !== review.reviewedAt
    || analysis.reviewMethod !== review.reviewMethod
    || JSON.stringify(analysis.metrics) !== JSON.stringify(metrics)
    || JSON.stringify(analysis.readingDemands || null) !== JSON.stringify(review.dimensionObservations || null)) {
    throw new Error(`${book.id}: public metadata and detailed analysis must use the same current review. Run node tools/generateGuidedReadingTextAnalysis.mjs first.`);
  }
  return {
    id: book.id,
    title: book.title,
    level: book.level,
    levelSystem: "literacy-guide-a-h-v1",
    appReadingLevel: review.appReadingLevel,
    textFingerprint,
    reviewedAt: review.reviewedAt,
    pageCount: metrics.pageCount,
    wordCount: metrics.wordCount,
    reviewedPageMedia: reviewedPageMedia(book),
    readingBandProfile: book.readingBandProfile || metadata?.readingBandProfile,
    readingMode: book.readingMode || metadata?.readingMode,
    ...(book.collection ? { collection: book.collection } : {})
  };
});

const banner = "// AUTO-GENERATED by tools/generateBookIndex.js - do not edit.\n";
const output = `${banner}export const GUIDED_READING_BOOK_INDEX = ${JSON.stringify(index)};\n`;
if (process.argv.includes("--check")) {
  if (fs.readFileSync(outFile, "utf8") !== output) throw new Error("Public book metadata index is stale. Run node tools/generateBookIndex.js --books-only.");
} else {
  fs.writeFileSync(outFile, output);
}
console.log(`book index: ${index.length} books -> ${path.relative(root, outFile)}`);
if (process.argv.includes("--books-only")) process.exit(0);

// ── Story questions for the quest's Story Stop station ────────────────────
// Built from the worlds' own book titles. Every question ships the book's COVER
// and printed TITLE, so the round is self-contained: the child reads the
// cover to answer - no prior reading of the book is assumed.
const { guidedReadingSeriesBooks } = await import(path.join(root, "src/data/guidedReadingSeriesBooks.js"));
const WORLD_SERIES = { meadow: "meadow-pals", dino: "dino-pals", moonwood: "moonwood-tales" };
const storyBank = {};
for (const [world, seriesId] of Object.entries(WORLD_SERIES)) {
  const books = guidedReadingSeriesBooks.filter(b => b.seriesId === seriesId);
  const questions = [];
  const names = new Set();
  for (const book of books) {
    const title = book.title;
    const cover = book.coverImage && fs.existsSync(path.join(root, "public", book.coverImage))
      ? book.coverImage
      : "";
    let m = title.match(/^([A-Z][a-z]+)'s (.+)$/);          // "Chompy's Big Lunch"
    if (m) {
      names.add(m[1]);
      questions.push({ prompt: "Whose story is this?", answer: m[1], title, cover });
      continue;
    }
    m = title.match(/^([A-Z][a-z]+) ((?:[A-Z][a-z']*|and|the|a|an|at|too|up|into)(?: .+)?)$/); // "Muddy Has a Bath"
    if (m && !["The", "What", "One", "Something"].includes(m[1]) && !m[2].startsWith("and ")) {
      names.add(m[1]);
      questions.push({ prompt: "Whose story is this?", answer: m[1], title, cover });
    }
  }
  storyBank[world] = { names: [...names], questions };
}
// Picture words verified against the actual files on disk - the asset
// manifest sometimes lists images that do not exist.
const { LETTER_EXAMPLES } = await import(path.join(root, "src/data/elSkillsBlockCycles.js"));
const { getChildWordAsset } = await import(path.join(root, "src/data/childAssets.js"));
const verified = [];
for (const word of new Set(Object.values(LETTER_EXAMPLES).flat().map(w => String(w).toLowerCase()))) {
  try {
    const asset = getChildWordAsset(word, { allowBlockedAssessmentImage: true });
    const image = asset?.image || asset?.fallbackImage;
    if (image && fs.existsSync(path.join(root, "public", image))) verified.push(word);
  } catch { /* skip */ }
}
const storyOut = path.join(root, "src", "data", "generated", "questStoryQuestions.generated.js");
fs.writeFileSync(storyOut, `${banner}export const QUEST_STORY_QUESTIONS = ${JSON.stringify(storyBank)};\nexport const VERIFIED_PICTURE_WORDS = ${JSON.stringify(verified.sort())};\n`);
console.log(`story questions: ${Object.values(storyBank).map(b => b.questions.length).join("/")} (meadow/dino/moonwood) -> ${path.relative(root, storyOut)}`);
