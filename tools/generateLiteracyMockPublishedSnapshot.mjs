import fs from 'node:fs';
import { createHash } from 'node:crypto';

// This is the already-published v1 contract, not a new hosted-data migration.
// Practice editorial changes must not change labels beneath server-owned keys.
const publications = [
  { version: 'v1', count: 3958, migration: '20261006092000_literacy_mock_items.sql' },
  { version: 'v2', count: 3976, migration: '20261010121000_literacy_mock_items_v2.sql' },
  { version: 'v3', count: 7549, migration: '20261010141000_literacy_mock_items_v3.sql', packed: true },
];
for (const publication of publications) {
const migration = new URL(`../supabase/migrations/${publication.migration}`, import.meta.url);
const output = new URL(`../src/data/generated/literacyMock${publication.version.toUpperCase()}.generated.js`, import.meta.url);
const sql = fs.readFileSync(migration, 'utf8');
const payload = publication.packed
  ? sql.match(/with packed as \(select '([\s\S]*?)'::jsonb as data\), decoded as materialized/)
  : sql.match(/from jsonb_array_elements\('([\s\S]*)'::jsonb\) item/);
if (!payload) throw new Error('Published mock manifest payload was not found.');
const encoded = JSON.parse(payload[1].replace(/''/g, "'"));
const unpack = node => typeof node === 'number' ? encoded.dictionary[node]
  : node[0] === 0 ? node.slice(1).map(unpack)
    : Object.fromEntries(Array.from({ length: (node.length - 1) / 2 }, (_, index) =>
      [encoded.dictionary[node[index * 2 + 1]], unpack(node[index * 2 + 2])]));
const items = publication.packed ? encoded.records.map(unpack) : encoded;
if (items.length !== publication.count || new Set(items.map(item => item.id)).size !== items.length) {
  throw new Error(`Published ${publication.version} coverage changed; review the version contract.`);
}
const sourceHash = createHash('sha256').update(sql).digest('hex');
const contents = `// Generated by tools/generateLiteracyMockPublishedSnapshot.mjs.\n`
  + `// Published literacy-mock-${publication.version} migration SHA-256: ${sourceHash}\n`
  + `// Preserve the private server manifest's exact labels, keys, snapshots and media.\n`
  + (publication.packed
    ? `const packed = ${JSON.stringify(encoded)};\n`
      + `const unpack = node => typeof node === 'number' ? packed.dictionary[node]\n`
      + `  : node[0] === 0 ? node.slice(1).map(unpack)\n`
      + `    : Object.fromEntries(Array.from({ length: (node.length - 1) / 2 }, (_, index) =>\n`
      + `      [packed.dictionary[node[index * 2 + 1]], unpack(node[index * 2 + 2])]));\n`
      + `export const LITERACY_MOCK_V3 = packed.records.map(unpack);\n`
    : `export const LITERACY_MOCK_${publication.version.toUpperCase()} = ${JSON.stringify(items.map(item => item.itemSnapshot))};\n`);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== contents) throw new Error(`Published mock ${publication.version} snapshot is stale.`);
} else {
  fs.writeFileSync(output, contents);
}
console.log(`Published ${publication.version} snapshot: ${items.length} items; source ${sourceHash.slice(0, 12)}.`);
}
