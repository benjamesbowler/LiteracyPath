import { createLiteracyMockManifest, compactIncomingSql } from './generateLiteracyMockManifest.mjs';
import { LITERACY_MOCK_V10_LADDERS } from '../src/policy/literacyMockDemandV10.js';

export const V10_CATALOGUE_MIGRATION = '20261016184807_literacy_mock_catalogue_v10.sql';
const literal = value => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;

export async function literacyMockV10CatalogueSql() {
  const previous = await createLiteracyMockManifest({ contentVersion: 'literacy-mock-v9' });
  const manifest = await createLiteracyMockManifest({ contentVersion: 'literacy-mock-v10' });
  const byId = new Map(previous.items.map(item => [item.id, item]));
  const additions = manifest.items.filter(item => !byId.has(item.id));
  if (byId.size + additions.length !== manifest.itemCount || previous.items.some(old => !manifest.items.some(item => item.id === old.id))) throw Error('V10 must preserve every earlier identity.');
  const routeKeys = new Set(['contentVersion','adaptiveAreaVersion','adaptiveAreaBand','adaptiveMixedEligible','adaptiveDemand']);
  const patches = {}, bands = {};
  for (const item of manifest.items) {
    if (item.itemSnapshot.adaptiveMixedEligible) bands[item.id] = item.itemSnapshot.adaptiveAreaBand;
    const old = byId.get(item.id);
    if (!old) continue;
    if (Object.keys(old.itemSnapshot).some(key => !Object.hasOwn(item.itemSnapshot, key))) throw Error(`V10 removed a historical snapshot property: ${item.id}`);
    const patch = Object.fromEntries(Object.entries(item.itemSnapshot).filter(([key, value]) => !routeKeys.has(key) && JSON.stringify(old.itemSnapshot[key]) !== JSON.stringify(value)));
    if (Object.keys(patch).length) patches[item.id] = patch;
    for (const key of Object.keys(old).filter(key => key !== 'itemSnapshot')) if (JSON.stringify(old[key]) !== JSON.stringify(item[key])) throw Error(`Changed existing item needs a new V10 identity: ${item.id} ${key}`);
  }
  return `-- Generated by tools/generateLiteracyMockV10.mjs. New canonical publication; do not rewrite V1-V9.
begin;
create temporary table literacy_mock_incoming(item jsonb not null) on commit drop;
${compactIncomingSql(additions)}
with source as (select item,item->'itemSnapshot' s from public.literacy_mock_items where content_version='literacy-mock-v9'),
route as (select ${literal(bands)} bands,${literal(patches)} patches,${literal(LITERACY_MOCK_V10_LADDERS)} ladders),
classified as (select source.*,case when bands?(s->>'id') then (bands->>(s->>'id'))::integer else null end band,patches,ladders from source cross join route),
snapshots as (select item,s||coalesce(patches->(s->>'id'),'{}'::jsonb)||jsonb_build_object('contentVersion','literacy-mock-v10','adaptiveAreaVersion','areas-v5','adaptiveAreaBand',band,'adaptiveMixedEligible',band is not null,'adaptiveDemand',case when band is null then 'null'::jsonb else ladders->(s->>'domainId')->band end) snapshot from classified)
insert into literacy_mock_incoming select jsonb_set(item,'{itemSnapshot}',snapshot) from snapshots;
do $$begin
 if (select count(*) from public.literacy_mock_items where content_version='literacy-mock-v9')<>${previous.itemCount} or (select count(*) from literacy_mock_incoming)<>${manifest.itemCount} then raise exception 'Incomplete V10 publication'; end if;
 if exists(select 1 from literacy_mock_incoming incoming join public.literacy_mock_items old on old.id=incoming.item->>'id' and old.content_version='literacy-mock-v10' where old.item is distinct from incoming.item) then raise exception 'Cannot rewrite immutable V10 publication'; end if;
end; $$;
insert into public.literacy_mock_items(id,content_version,item) select item->>'id','literacy-mock-v10',item from literacy_mock_incoming on conflict(id,content_version) do nothing;
insert into public.literacy_mock_publications(content_version,item_count) values('literacy-mock-v10',${manifest.itemCount}) on conflict(content_version) do nothing;
do $$begin
 if (select count(*) from public.literacy_mock_items where content_version='literacy-mock-v10')<>${manifest.itemCount} or not exists(select 1 from public.literacy_mock_publications where content_version='literacy-mock-v10' and item_count=${manifest.itemCount}) then raise exception 'V10 publication count mismatch'; end if;
end; $$;
commit;
`;
}
