import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

import { GUIDED_READING_IMAGE_REVISIONS } from "../src/data/generated/guidedReadingImageRevisions.generated.js";
import { guidedReadingReplacementImagePath } from "../src/utils/guidedReading/mediaVersion.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
const scopeModule = path.join(root, "src/data/generated/guidedReadingImmutableDeliveryPaths.generated.js");

// Scope follows the existing accepted review receipts; this is not a new image
// approval registry. The immutable paths still use the shared reviewed hashes.
export async function reviewedSiblingImageDeliveries() {
  const repair = JSON.parse(await fs.readFile(path.join(root, "source-art/guided-reading-remediation/2026-11-11/image-repairs.json"), "utf8"));
  const grounding = JSON.parse(await fs.readFile(path.join(root, "source-art/world-discovery/remediation/2026-11-11/d04-complete-book-review.json"), "utf8"));
  const images = repair.entries.map(entry => {
    if (entry.finalReview?.status !== "accepted") throw Error("Sibling delivery has no accepted image review");
    return { path: entry.output.publicPath, sha256: entry.output.sha256 };
  });
  for (const book of grounding.books) for (const asset of book.assets) {
    if (asset.replaced && asset.path.startsWith("public/guided-reading/")) images.push({ path: asset.path.slice("public".length), sha256: asset.sha256 });
  }
  if (new Set(images.map(image => image.path)).size !== images.length) throw Error("Duplicate sibling image review path");
  return images.sort((left, right) => left.path.localeCompare(right.path));
}

const scopeSource = images => "// Generated by node tools/buildGuidedReadingReplacementImages.mjs.\n"
  + "// Delivery scope from the accepted Nov11 image-repair and D04 review receipts;\n"
  + "// image-byte authority remains GUIDED_READING_IMAGE_REVISIONS and those reviews.\n"
  + "export const GUIDED_READING_IMMUTABLE_DELIVERY_PATHS = Object.freeze(" + JSON.stringify(images.map(image => image.path), null, 2) + ");\n";

// No artwork is generated or re-encoded here. Existing review revisions own
// source identity; this is a delivery copy for already-installed old workers.
export async function buildGuidedReadingReplacementImages({ publicRoot = path.join(root, "public"), revisions = GUIDED_READING_IMAGE_REVISIONS, additionalImages, check = false } = {}) {
  const reviewedSiblings = additionalImages ?? await reviewedSiblingImageDeliveries();
  const additionalPaths = new Set(reviewedSiblings.map(image => image.path));
  for (const image of reviewedSiblings) {
    if (!image.path.startsWith("/guided-reading/") || revisions[image.path] !== image.sha256?.slice(0, 12)) {
      throw Error(`Sibling delivery does not match its existing reviewed revision: ${image.path}`);
    }
    if (hash(await fs.readFile(path.join(publicRoot, image.path))) !== image.sha256) throw Error(`Sibling image changed after review: ${image.path}`);
  }
  const results = [];
  for (const [canonical, revision] of Object.entries(revisions)) {
    const delivery = guidedReadingReplacementImagePath(canonical, revision, additionalPaths);
    if (delivery === canonical) continue;
    const source = await fs.readFile(path.join(publicRoot, canonical));
    const sourceSha256 = hash(source);
    if (sourceSha256.slice(0, 12) !== revision) throw Error(`Stale reviewed image revision: ${canonical}`);
    const target = path.join(publicRoot, delivery);
    const prior = await fs.readFile(target).catch(error => {
      if (error.code !== "ENOENT") throw error;
      return null;
    });
    if (prior && !prior.equals(source)) throw Error(`Replacement delivery bytes changed: ${delivery}`);
    if (!prior) {
      if (check) throw Error(`Missing replacement image delivery: ${delivery}`);
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, source, { flag: "wx" });
    }
    results.push({ canonical, delivery, sha256: sourceSha256, bytes: source.length });
  }
  if (!results.length) throw Error("No reviewed replacement image deliveries were found");
  return results;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length > 1 || args.some(arg => arg !== "--check")) throw Error("Usage: buildGuidedReadingReplacementImages.mjs [--check]");
  const additionalImages = await reviewedSiblingImageDeliveries();
  const expectedScope = scopeSource(additionalImages);
  if (args.includes("--check")) {
    if (await fs.readFile(scopeModule, "utf8") !== expectedScope) throw Error("Sibling immutable delivery scope is stale");
  }
  const results = await buildGuidedReadingReplacementImages({ additionalImages, check: args.includes("--check") });
  if (!args.includes("--check")) await fs.writeFile(scopeModule, expectedScope);
  console.log(`${args.includes("--check") ? "Verified" : "Prepared"} ${results.length} exact full-resolution replacement image deliveries (${results.reduce((sum, row) => sum + row.bytes, 0)} bytes).`);
}
