import {normalizeLedaAudioText} from '../src/data/normalizeLedaAudioText.js';
const root=process.cwd(),source='src/data/generated/literacyMockAudioV11.generated.js';
const base=await loadLiteracyMockBank({contentVersion:'literacy-mock-v10',includeUnavailable:true});
const requests=[...listFoundationInstructionsV11AudioGaps(),...listMeaningChoicesV11AudioGaps(base),...listLiteracyMockEverydayCapacityV11AudioGaps(base,source=>normalizeLiteracyMockItem(source,{contentVersion:'literacy-mock-v11'}))];
const verifyOnly=process.argv.includes('--verify');
const token=(!verifyOnly && requests.length) ? execFileSync('gcloud',['auth','application-default','print-access-token'],{encoding:'utf8'}).trim() : '';
const project=process.env.GOOGLE_CLOUD_PROJECT||'project-3c66c1c8-cc9e-4d6d-bdf';
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'literacy-v11-audio-')),metadata=structuredClone(LITERACY_MOCK_V11_AUDIO_METADATA),byRole=structuredClone(LITERACY_MOCK_V11_AUDIO_BY_ROLE);
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const hash=text=>createHash('sha256').update(text).digest('hex');
function save(){fs.writeFileSync(source,`// Generated by tools/generateLiteracyMockV11Audio.mjs. Exact new V11 scripts only.\nexport const LITERACY_MOCK_V11_AUDIO_BY_ROLE=Object.freeze(${JSON.stringify(byRole,null,2)});\nexport const LITERACY_MOCK_V11_AUDIO_METADATA=Object.freeze(${JSON.stringify(metadata,null,2)});\n`);}
async function generate(row,index){
 const key=normalizeLedaAudioText(row.text),id=hash(`${LEDA_PRODUCTION_VOICE}|${row.role}|${row.text}|v11`).slice(0,18);
 const publicPath=`/audio/production/en-US/mock-v11/${id}.mp3`,out=path.join(root,'public',publicPath),wav=path.join(temp,`${id}.wav`);
 if(!fs.existsSync(out)){
  let response;
  for(let attempt=0;attempt<5;attempt++){
   response=await fetch('https://texttospeech.googleapis.com/v1/text:synthesize',{method:'POST',headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json','x-goog-user-project':project},body:JSON.stringify({input:{text:row.text},voice:{languageCode:'en-US',name:LEDA_PRODUCTION_VOICE},audioConfig:{audioEncoding:'LINEAR16',sampleRateHertz:24000,speakingRate:0.94}})});
   if(response.ok)break;
   if(![429,500,502,503,504].includes(response.status))throw Error(`Audio generation HTTP${response.status}`);
   await sleep(1000*2**attempt);
  }
  if(!response.ok)throw Error(`Audio generation HTTP${response.status}`);
  const data=await response.json();if(!data.audioContent)throw Error('Missing generated audio');
  fs.writeFileSync(wav,Buffer.from(data.audioContent,'base64'));
  fs.mkdirSync(path.dirname(out),{recursive:true});
  execFileSync('ffmpeg',['-v','error','-y','-i',wav,'-af','loudnorm=I=-18:TP=-2:LRA=7','-ar','24000','-ac','1','-b:a','48k',out]);fs.unlinkSync(wav);
 }
 const duration=Number(execFileSync('ffprobe',['-v','error','-show_entries','format=duration','-of','default=noprint_wrappers=1:nokey=1',out],{encoding:'utf8'}).trim());
 const probe=execFileSync('ffmpeg',['-v','error','-i',out,'-f','null','-'],{encoding:'utf8'});
 if(!duration||probe===null)throw Error('Undecodable recording');
 byRole[row.role]||={};byRole[row.role][key]=publicPath;
 metadata[`${row.role}:${key}`]={text:row.text,role:row.role,audio:publicPath,voice:LEDA_PRODUCTION_VOICE,provider:'Google Cloud Text-to-Speech',aiGenerated:true,sha256:hash(fs.readFileSync(out)),durationSeconds:duration,humanListening:'unknown'};
 save();if(index%20===0)console.log(`Recorded ${index+1}/${requests.length}`);
}
if(verifyOnly && requests.length)throw Error(`${requests.length} exact V11 recordings are unresolved.`);
try{for(let index=0;index<requests.length;index+=2)await Promise.all(requests.slice(index,index+2).map((row,offset)=>generate(row,index+offset)));const publication=await loadLiteracyMockBank({contentVersion:'literacy-mock-v11',includeUnavailable:true});
 const used=new Set(publication.flatMap(item=>item.requiredAudioPaths));
 if(process.argv.includes('--prune')){
  let removed=0;
  for(const [key,row]of Object.entries(metadata))if(!used.has(row.audio)){
   delete metadata[key];delete byRole[row.role]?.[normalizeLedaAudioText(row.text)];
   const file=path.join(root,'public',row.audio);
   if(fs.existsSync(file)){fs.unlinkSync(file);removed++;}
  }
  console.log(`Removed ${removed} reproducible unused task recordings.`);
 }
 for(const row of Object.values(metadata)){
  const file=path.join(root,'public',row.audio),bytes=fs.readFileSync(file);
  if(!bytes.length || hash(bytes)!==row.sha256 || row.voice!==LEDA_PRODUCTION_VOICE)throw Error('V11 recording metadata/bytes mismatch');
 }
 if(!verifyOnly||process.argv.includes('--prune'))save();
 console.log(`Verified ${Object.keys(metadata).length} exact V11 recordings.`);}
finally{fs.rmSync(temp,{recursive:true,force:true});}
