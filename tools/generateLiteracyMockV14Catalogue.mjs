import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compactIncomingSql, createLiteracyMockManifest } from './generateLiteracyMockManifest.mjs';

export const V14_CATALOGUE_MIGRATION = '20261124090100_literacy_mock_catalogue_v14.sql';
const root = new URL('../', import.meta.url);
const quote = value => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;

export async function literacyMockV14CatalogueSql() {
  const [previous, manifest] = await Promise.all(['literacy-mock-v13', 'literacy-mock-v14']
    .map(contentVersion => createLiteracyMockManifest({ contentVersion })));
  const byId = new Map(previous.items.map(item => [item.id, item]));
  const inherited = new Set();
  const corrected = manifest.items.filter(item => {
    const old = byId.get(item.id);
    if (!old || JSON.stringify(item) !== JSON.stringify({ ...old,
      itemSnapshot: { ...old.itemSnapshot, contentVersion: manifest.contentVersion } })) return true;
    inherited.add(item.id);
    return false;
  });
  const excluded = previous.items.filter(item => !inherited.has(item.id)).map(item => item.id);
  return `-- Generated by tools/generateLiteracyMockV14Catalogue.mjs. Unified assessment bank for both entry points.
begin;
create temporary table literacy_mock_incoming(item jsonb not null) on commit drop;
${compactIncomingSql(corrected)}
insert into literacy_mock_incoming
select jsonb_set(item,'{itemSnapshot,contentVersion}','"literacy-mock-v14"'::jsonb)
from public.literacy_mock_items where content_version='literacy-mock-v13'
 and not (${quote(excluded)} ? id);
do $$begin
 if (select count(*) from literacy_mock_incoming) <> ${manifest.itemCount}
  or (select count(distinct item->>'id') from literacy_mock_incoming) <> ${manifest.itemCount} then
  raise exception 'Incomplete V14 scored bank or V13 prerequisite';
 end if;
 if exists(select 1 from literacy_mock_incoming incoming join public.literacy_mock_items old
  on old.id=incoming.item->>'id' and old.content_version='literacy-mock-v14'
  where old.item is distinct from incoming.item) then raise exception 'Cannot rewrite immutable V14 publication'; end if;
 if exists(select 1 from public.literacy_mock_publications where content_version='literacy-mock-v14' and item_count<>${manifest.itemCount}) then
  raise exception 'Published mock catalogue count is immutable';
 end if;
end; $$;
insert into public.literacy_mock_items(id,content_version,item)
select item->>'id','literacy-mock-v14',item from literacy_mock_incoming on conflict(id,content_version) do nothing;
insert into public.literacy_mock_publications(content_version,item_count)
values('literacy-mock-v14',${manifest.itemCount}) on conflict(content_version) do nothing;
do $$begin
 if (select count(*) from public.literacy_mock_items where content_version='literacy-mock-v14')<>${manifest.itemCount}
  then raise exception 'Incomplete V14 publication'; end if;
end; $$;
notify pgrst,'reload schema';
commit;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const path = new URL(`supabase/migrations/${V14_CATALOGUE_MIGRATION}`, root);
  const sql = await literacyMockV14CatalogueSql();
  if (process.argv.includes('--check')) assert.equal(fs.readFileSync(path, 'utf8'), sql);
  else fs.writeFileSync(path, sql);
  console.log(`${V14_CATALOGUE_MIGRATION}: ${Buffer.byteLength(sql)} bytes; local publication only.`);
}
