import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { LITERACY_MOCK_AREA_MAX } from '../src/policy/literacyMockAdaptivePolicy.js';
import { LITERACY_MOCK_CONTINUOUS_EXCLUDED_IDS } from '../src/policy/literacyMockContinuousRouting.js';
import { V14_SCHEMA_MIGRATION } from './generateLiteracyMockV14Schema.mjs';

export const CONTINUOUS_ROUTING_MIGRATION = '20261124120000_literacy_mock_continuous_routing.sql';
const migrations = new URL('../supabase/migrations/', import.meta.url);
const read = name => fs.readFileSync(new URL(name, migrations), 'utf8');

function replaceOnce(source, before, after) {
  assert.equal(source.split(before).length, 2, 'Expected one V14 schema anchor: ' + before);
  return source.replace(before, () => after);
}

export function literacyMockContinuousRoutingSql() {
  const previous = read(V14_SCHEMA_MIGRATION);
  function definition(name) {
    const start = previous.indexOf('create or replace function public.' + name + '(');
    const end = previous.indexOf('end; $$;', start);
    assert.ok(start >= 0 && end > start);
    return previous.slice(start, end + 'end; $$;'.length);
  }

  // The preparation fingerprint includes the policy so a retry across the two
  // public entry points cannot change the routing contract of a saved sitting.
  let prepare = definition('lp_mock_prepare_v14_before_delivery');
  prepare = replaceOnce(prepare, 'lp_mock_prepare_v14_before_delivery', 'teacher_prepare_literacy_mock_continuous_session');
  prepare = replaceOnce(prepare, "text default 'pause_at_window_end'", "text default 'untimed'");
  prepare = replaceOnce(prepare, "not in ('pause_at_window_end','timed_sample')", "not in ('pause_at_window_end','timed_sample','untimed')");
  prepare = replaceOnce(prepare, "'windowMode',p_window_mode,'version'", "'routingPolicy','continuous-v1','windowMode',p_window_mode,'version'");
  prepare = replaceOnce(prepare, 'window_mode,fresh_sampling)', 'window_mode,fresh_sampling,delivery_mode,routing_policy)');
  prepare = replaceOnce(prepare, 'p_window_mode,true);', "p_window_mode,true,case when p_window_mode='untimed' then 'collect' else 'live' end,'continuous-v1');");

  // Historical domain-local placeholders, the frozen presentation override
  // and exact-condition media repair continue to use the published validator.
  let plan = definition('lp_mock_boundary_plan_error_v9');
  plan = replaceOnce(plan, 'v_limit integer;', 'v_limit integer; v_continuous boolean;');
  plan = replaceOnce(plan, 'select item_count into v_limit', "select item_count,coalesce(routing_policy='continuous-v1',false) into v_limit,v_continuous");
  plan = replaceOnce(plan, ' v_states:=public.lp_mock_boundary_state_for_version(v_rows,v_version);', ` -- Check all future admissions before either adaptation or the repair shortcut.
 if v_continuous and exists(select 1 from jsonb_array_elements_text(p_plan->'itemIds') with ordinality p(id,slot)
   where p.slot>p_answered and public.lp_mock_continuous_item_excluded(p.id)) then
   return 'content_item_withdrawn'; end if;
 v_states:=public.lp_mock_boundary_state_for_version(v_rows,v_version);`);
  plan = replaceOnce(plan, '  if v_index=p_answered+1 and jsonb_array_length(v_reserved)>p_answered then',
    `  if v_continuous and v_index=p_answered+1 then
   v_expected:=public.lp_mock_continuous_next_band(v_rows,v_domain);
  end if;
  if v_index=p_answered+1 and jsonb_array_length(v_reserved)>p_answered then`);
  // A future candidate must still be fresh, published, mixed-eligible and
  // from its scheduled domain. Its demand becomes binding at the next slot.
  plan = replaceOnce(plan, 'if v_band is distinct from v_expected then',
    'if (not v_continuous or v_index=p_answered+1) and v_band is distinct from v_expected then');

  let event = definition('student_record_literacy_mock_event');
  event = replaceOnce(event, 'if public.lp_literacy_item_quarantined(v_item) then',
    "if public.lp_literacy_item_quarantined(v_item) or (v_mock->>'routing_policy'='continuous-v1' and public.lp_mock_continuous_item_excluded(p_question_id)) then");
  event = replaceOnce(event, "is distinct from (v_states#>>array[v_item->>'domainId','nextBand'])::integer then",
    `is distinct from (case when v_mock->>'routing_policy'='continuous-v1'
     then public.lp_mock_continuous_next_band(v_rows,v_item->>'domainId')
     else (v_states#>>array[v_item->>'domainId','nextBand'])::integer end) then`);

  return `-- Generated by tools/generateLiteracyMockContinuousRouting.mjs.
begin;

alter table public.literacy_mock_sessions add column routing_policy text
  check (routing_policy is null or (routing_policy='continuous-v1' and plan_kind='mixed'));

create function public.lp_mock_continuous_item_excluded(p_id text)
returns boolean language sql immutable set search_path='' as $$
  select '${JSON.stringify(LITERACY_MOCK_CONTINUOUS_EXCLUDED_IDS)}'::jsonb ? p_id;
$$;
revoke all on function public.lp_mock_continuous_item_excluded(text) from public,anon,authenticated;

create function public.lp_mock_continuous_next_band(p_rows jsonb,p_domain text)
returns integer language plpgsql immutable set search_path='' as $$
declare
  v_maxima constant jsonb:='${JSON.stringify(LITERACY_MOCK_AREA_MAX)}'::jsonb;
  v_row jsonb; v_item jsonb; v_band integer; v_previous_max integer;
  v_max integer:=(v_maxima->>p_domain)::integer; v_position numeric;
begin
  if v_max is null then return null; end if;
  select value into v_row from jsonb_array_elements(p_rows) with ordinality r(value,slot)
    where value->>'responseStatus' is distinct from 'media_failed' order by slot desc limit 1;
  if not found then return 1; end if;
  v_item:=coalesce(v_row->'itemSnapshot',v_row->'questionSnapshot',v_row);
  v_band:=public.lp_mock_area_band(jsonb_build_object('itemSnapshot',v_item));
  v_previous_max:=(v_maxima->>(v_item->>'domainId'))::integer;
  if v_previous_max is null or v_band is null or v_band not between 0 and v_previous_max then return null; end if;
  v_position:=v_band::numeric*v_max/v_previous_max;
  if (v_row ? 'classification' and v_row->>'classification'<>'independent')
    or not public.lp_literacy_response_eligible(v_row) then return round(v_position)::integer; end if;
  if (v_row->>'isCorrect')::boolean then return least(v_max,floor(v_position)::integer+1); end if;
  return greatest(0,ceil(v_position)::integer-1);
end; $$;
revoke all on function public.lp_mock_continuous_next_band(jsonb,text) from public,anon,authenticated;

${plan}
revoke all on function public.lp_mock_boundary_plan_error_v9(uuid,uuid,jsonb,jsonb,integer,jsonb) from public,anon,authenticated;

${event}
revoke all on function public.student_record_literacy_mock_event(text,uuid,text,text,text) from public,anon,authenticated;
grant execute on function public.student_record_literacy_mock_event(text,uuid,text,text,text) to anon,authenticated;

${prepare}
revoke all on function public.teacher_prepare_literacy_mock_continuous_session(uuid,uuid[],boolean,integer,integer,text,text) from public,anon,authenticated;
grant execute on function public.teacher_prepare_literacy_mock_continuous_session(uuid,uuid[],boolean,integer,integer,text,text) to authenticated;

notify pgrst,'reload schema';
commit;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sql = literacyMockContinuousRoutingSql();
  if (process.argv.includes('--check')) assert.equal(read(CONTINUOUS_ROUTING_MIGRATION), sql);
  else fs.writeFileSync(new URL(CONTINUOUS_ROUTING_MIGRATION, migrations), sql);
}
