import assert from 'node:assert/strict';
import fs from 'node:fs';
import { LITERACY_MOCK_V14_PICTURE_ISSUES } from '../src/policy/literacyItemEligibility.js';

const migrations = new URL('../supabase/migrations/', import.meta.url);
const previous = fs.readFileSync(new URL('20261028040000_literacy_mock_beginner_vocabulary.sql', migrations), 'utf8');
const original = previous.match(/create or replace function public\.lp_literacy_item_quality_issue\([\s\S]*?\$\$;/)?.[0];
assert.ok(original, 'The previous published quality rules must be preserved.');
const reasons = JSON.stringify(LITERACY_MOCK_V14_PICTURE_ISSUES).replaceAll("'", "''");
const sql = `-- Generated by tools/generateLiteracyMockV14PictureQuarantine.mjs.
-- Existing catalogue rows and saved responses retain their original bytes.
begin;
${original.replace('public.lp_literacy_item_quality_issue(', 'public.lp_literacy_quality_before_v14_pictures(')}
revoke all on function public.lp_literacy_quality_before_v14_pictures(jsonb) from public,anon,authenticated;
create or replace function public.lp_literacy_item_quality_issue(p_value jsonb)
returns jsonb language sql immutable set search_path='' as $$
 with source as materialized (
   select coalesce(nullif(p_value->'itemSnapshot','null'::jsonb),nullif(p_value->'questionSnapshot','null'::jsonb),nullif(p_value->'question','null'::jsonb),p_value) s
 ), reviewed as (
   select s, '${reasons}'::jsonb->>(s->>'id') reason from source
 )
 select case when s->>'contentVersion'='literacy-mock-v14' and reason is not null
   then jsonb_build_object('code','ambiguous_picture','reason',reason)
   else public.lp_literacy_quality_before_v14_pictures(p_value) end from reviewed;
$$;
revoke all on function public.lp_literacy_item_quality_issue(jsonb) from public,anon,authenticated;
notify pgrst,'reload schema';
commit;
`;
const target = new URL('20261124090200_literacy_mock_v14_picture_quarantine.sql', migrations);
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8'), sql);
else fs.writeFileSync(target, sql);
