function collectChunkClosure(bundle, seeds, { includeDynamic = false } = {}) {
  const selected = new Set();
  const visit = fileName => {
    if (!fileName || selected.has(fileName)) return;
    const item = bundle[fileName];
    if (!item || item.type !== "chunk") return;
    selected.add(fileName);
    const imports = includeDynamic
      ? [...(item.imports || []), ...(item.dynamicImports || [])]
      : item.imports || [];
    for (const imported of imports) visit(imported);
  };
  for (const seed of seeds) visit(seed);
  return selected;
}

function assessmentFonts(bundle, styles) {
  const fonts = new Set();
  for (const name of styles) {
    const css = String(bundle[name]?.source || '');
    for (const [face] of css.matchAll(/@font-face\s*\{[^}]*\}/g)) {
      // The assessment is English. Fontsource includes every script in its CSS;
      // browsers normally fetch only the face selected by unicode-range.
      if (/unicode-range\s*:/i.test(face) && !/U\+0{0,3}0-0{0,2}FF\b/i.test(face)) continue;
      const sources=[...face.matchAll(/url\(\s*["']?(?:\/)?(assets\/[^\s)"']+\.woff2?)["']?\s*\)/g)].map(match=>match[1]);
      const preferred=sources.filter(path=>path.endsWith('.woff2'));
      for(const path of preferred.length?preferred:sources)if(bundle[path])fonts.add(path);
    }
  }
  return [...fonts];
}

export function serviceWorkerSource({ buildId, precache, questAssets = [], mockAssets = [] }) {
  return `/* ${PRODUCT_NAME} offline shell ${buildId}. Generated by Vite. */
const BUILD_ID = ${JSON.stringify(buildId)};
const SHELL_PREFIX = "lp-shell-";
const SHELL_CACHE = SHELL_PREFIX + BUILD_ID;
const QUEST_MEDIA_CACHE = "lp-quest-media-v1";
const PRECACHE = ${JSON.stringify(precache)};
const QUEST_EXECUTABLE_ASSETS = ${JSON.stringify(questAssets)};
const MOCK_EXECUTABLE_ASSETS = ${JSON.stringify(mockAssets)};
const QUEST_MEDIA_PREFIXES = [
  "/guided-reading/",
  "/audio/production/en-US/guided_page/",
  "/game-assets/quest-pixel/",
  "/game-assets/sound-seekers/worlds/",
  "/game-assets/sound-seekers/characters/",
  "/game-assets/sound-seekers/question-art/",
  "/images/sound-seekers/questions/",
  "/audio/music/quest/",
  "/game-assets/sound-seekers/v2/",
  "/audio/quest-v2/",
  ...${JSON.stringify(CAMPAIGN_OFFLINE_AUDIO_PREFIXES)}
];

function isQuestMedia(pathname) {
  return QUEST_MEDIA_PREFIXES.some(prefix => pathname.startsWith(prefix));
}

function isCacheable(response) {
  // CacheStorage rejects 206 Partial Content responses. Media elements request
  // byte ranges, so treating every successful 2xx response as cacheable turns
  // valid streamed audio into a service-worker network failure.
  return Boolean(response && response.status === 200 && (response.type === "basic" || response.type === "default"));
}

async function notifyClients(message) {
  const clients = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
  for (const client of clients) client.postMessage({ ...message, buildId: BUILD_ID });
}

self.addEventListener("install", event => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL_CACHE);
    let index = 0, failed = false;
    const workers = await Promise.allSettled(Array.from({ length: Math.min(4, PRECACHE.length) }, async () => {
      try {
        while (!failed && index < PRECACHE.length) {
          const url = PRECACHE[index++];
          // Reuse hashed HTTP-cache hits; overlap slow connection waits.
          const response = await fetch(new Request(url, { cache: url.startsWith("/assets/") ? "default" : "reload", credentials: "same-origin" }));
          if (!isCacheable(response)) throw new Error("Offline precache failed: " + url);
          await cache.put(url, response);
        }
      } catch (error) { failed = true; throw error; }
    }));
    const rejected = workers.find(row => row.status === "rejected");
    if (rejected) throw rejected.reason;
  })());
});

self.addEventListener("activate", event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names
      .filter(name => name.startsWith(SHELL_PREFIX) && name !== SHELL_CACHE)
      .map(name => caches.delete(name)));
    await self.clients.claim();
    await notifyClients({ type: "LP_OFFLINE_SHELL_READY", precached: PRECACHE.length });
  })());
});

async function navigationResponse(request) {
  const shell = await caches.open(SHELL_CACHE);
  const retained = async () => {
    const direct = await shell.match(request, { ignoreSearch: true });
    if (direct) return direct;
    const url = new URL(request.url);
    const fallback = url.pathname.startsWith("/preview/") ? "/preview/quest.html" : "/index.html";
    return shell.match(fallback, { ignoreSearch: true });
  };
  try {
    const response = await fetch(request);
    // Intermittent Wi-Fi/gateways can return 5xx instead of rejecting fetch.
    // Keep the retained app open so its durable answers can recover normally.
    if (response.status >= 500) return (await retained()) || response;
    if (isCacheable(response)) await shell.put(request, response.clone());
    return response;
  } catch {
    return retained();
  }
}

async function cacheFirst(request, cacheName) {
  const cache = await caches.open(cacheName);
  const cached = await cache.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (isCacheable(response)) await cache.put(request, response.clone());
  return response;
}

async function questMediaResponse(request) {
  const cache = await caches.open(QUEST_MEDIA_CACHE);
  const cached = await cache.match(request, { ignoreSearch: true });
  // A complete response warmed earlier is safe to serve to a media element
  // while offline. Otherwise forward byte-range requests without caching: a
  // 206 response cannot be stored in CacheStorage.
  if (request.headers.has("range")) return cached || fetch(request);
  const update = fetch(request).then(async response => {
    if (isCacheable(response)) await cache.put(request, response.clone());
    return response;
  });
  if (cached) {
    update.catch(() => {});
    return cached;
  }
  return update;
}

self.addEventListener("fetch", event => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (request.mode === "navigate") {
    event.respondWith(navigationResponse(request));
    return;
  }
  if (url.pathname.startsWith("/assets/") || PRECACHE.includes(url.pathname)) {
    event.respondWith(cacheFirst(request, SHELL_CACHE));
    return;
  }
  if (isQuestMedia(url.pathname)) event.respondWith(questMediaResponse(request));
});

self.addEventListener("message", event => {
  const data = event.data || {};
  // Keep normal releases on the safe "activate after clients close" policy,
  // while allowing an explicit same-origin recovery action to replace a
  // broken active worker without asking a child to find and close every tab.
  if (data.type === "LP_ACTIVATE_UPDATE") {
    event.waitUntil(self.skipWaiting());
    return;
  }
  if (data.type === "LP_OFFLINE_STATUS") {
    event.source?.postMessage({ type: "LP_OFFLINE_SHELL_READY", buildId: BUILD_ID, precached: PRECACHE.length });
    return;
  }
  if (data.type === "LP_OFFLINE_UPDATE_STATUS") {
    event.source?.postMessage({ type: "LP_OFFLINE_UPDATE_READY", buildId: BUILD_ID, precached: PRECACHE.length });
    return;
  }
  if (data.type === "LP_WARM_MOCK_EXECUTABLE") {
    event.waitUntil((async () => {
      const cache = await caches.open(SHELL_CACHE); let failed=0;
      for (const url of MOCK_EXECUTABLE_ASSETS) {
        try {
          if (await cache.match(url)) continue;
          const response=await fetch(new Request(url,{credentials:"omit"}));
          if (!isCacheable(response)) throw new Error("Uncacheable assessment executable");
          await cache.put(url,response);
        } catch { failed++; }
      }
      event.source?.postMessage({type:"LP_MOCK_EXECUTABLE_READY",requestId:data.requestId,buildId:BUILD_ID,
        requested:MOCK_EXECUTABLE_ASSETS.length,failed});
    })()); return;
  }
  if (data.type === "LP_WARM_QUEST_EXECUTABLE") {
    event.waitUntil((async () => {
      const cache = await caches.open(SHELL_CACHE);
      let failed = 0;
      for (const url of QUEST_EXECUTABLE_ASSETS) {
        try {
          if (await cache.match(url)) continue;
          const response = await fetch(new Request(url, { credentials: "same-origin" }));
          if (!isCacheable(response)) throw new Error("Uncacheable response");
          await cache.put(url, response);
        } catch { failed += 1; }
      }
      event.source?.postMessage({ type: "LP_QUEST_EXECUTABLE_READY", buildId: BUILD_ID, failed });
    })());
    return;
  }
  if (data.type !== "LP_WARM_QUEST_ASSETS") return;
  event.waitUntil((async () => {
    const urls = [...new Set(Array.isArray(data.urls) ? data.urls : [])]
      .map(value => new URL(value, self.location.origin))
      .filter(url => url.origin === self.location.origin && isQuestMedia(url.pathname));
    const cache = await caches.open(QUEST_MEDIA_CACHE);
    let completed = 0;
    let failed = 0;
    for (const url of urls) {
      try {
        const response = await fetch(new Request(url.href, { credentials: "same-origin" }));
        if (!isCacheable(response)) throw new Error("Uncacheable response");
        await cache.put(url.href, response);
        completed += 1;
      } catch {
        const existing = await cache.match(url.href, { ignoreSearch: true });
        if (existing) completed += 1;
        else failed += 1;
      }
    }
    event.source?.postMessage({
      type: "LP_QUEST_WARM_COMPLETE",
      buildId: BUILD_ID,
      requestId: data.requestId || "",
      chapterId: data.chapterId || "",
      requested: urls.length,
      completed,
      failed
    });
  })());
});
`;
}

export function questOfflinePlugin({ includeQuestPreview = false, buildVariant = "" } = {}) {
  return {
    name: "literacy-path-quest-offline",
    apply: "build",
    // Run after Vite prunes CSS-only JS chunks and transfers their styles.
    // A single removed placeholder in precache rejects the entire install.
    generateBundle: { order: "post", handler(_, bundle) {
      const chunks = Object.values(bundle).filter(item => item.type === "chunk");
      const entries = chunks.filter(chunk => chunk.isEntry).map(chunk => chunk.fileName);
      const questEntries = chunks
        .filter(chunk => /QuestRoot|QuestPixelWorld/.test(chunk.fileName)
          || /\/QuestRoot\.jsx$|\/QuestPixelWorld\.jsx$/.test(chunk.facadeModuleId || ""))
        .map(chunk => chunk.fileName);
      const v2QuestEntries = chunks
        .filter(chunk => /SoundSeekersRoute/.test(chunk.fileName)
          || /\/SoundSeekersRoute\.jsx$/.test(chunk.facadeModuleId || ""))
        .map(chunk => chunk.fileName);
      const legacyQuestEntries = questEntries.filter(fileName => !v2QuestEntries.includes(fileName));
      const questExecutableMode = v2QuestEntries.length ? "v2" : "legacy";
      const questExecutableRoots = questExecutableMode === "v2" ? v2QuestEntries : legacyQuestEntries;
      const questExecutableClosure = collectChunkClosure(bundle, questExecutableRoots, { includeDynamic: true });
      const questExecutable = {
        mode: questExecutableMode,
        cachePolicy: includeQuestPreview ? "precache" : "on-demand",
        roots: questExecutableRoots.map(fileName => `/${fileName}`).sort(),
        graph: [...questExecutableClosure].sort().map(fileName => {
          const chunk = bundle[fileName];
          return {
            url: `/${fileName}`,
            imports: [...new Set([...(chunk.imports || []), ...(chunk.dynamicImports || [])]
              .filter(imported => questExecutableClosure.has(imported)))]
              .map(imported => `/${imported}`).sort()
          };
        })
      };
      // First install needs sign-in and Home. Activities and their styles are
      // cached when opened; the dedicated offline preview still warms its fixture.
      const homeEntries = chunks.filter(chunk => Object.keys(chunk.modules || {})
        .some(id => /\/(AppSurface|StudentHomePage|StudentGlassShell)\.jsx$/.test(id)))
        .map(chunk => chunk.fileName);
      const moduleRoots=pattern=>chunks.filter(chunk=>Object.keys(chunk.modules || {}).some(id=>pattern.test(id))).map(chunk=>chunk.fileName);
      // The validated client loads these lazily. They are still required when
      // resuming a real signed-in child after an offline navigation.
      const boundaryRoots=moduleRoots(/\/src\/data\/boundaries\/(?:client|auth)\.js$/);
      const selectedChunks = collectChunkClosure(bundle, [...entries, ...homeEntries, ...boundaryRoots]);
      if (includeQuestPreview) {
        for (const fileName of questExecutableClosure) selectedChunks.add(fileName);
      }
      const chunkStyles = files => [...new Set([...files].flatMap(fileName =>
        [...(bundle[fileName]?.viteMetadata?.importedCss || [])]))];
      const questAssets = [...questExecutableClosure, ...chunkStyles(questExecutableClosure)]
        .map(fileName => `/${fileName}`).sort();
      questExecutable.assets = questAssets;
      const mockRoots=moduleRoots(/\/LiteracyMockPage\.jsx$/);
      const mockPack=extra=>{
        const closure=collectChunkClosure(bundle,[...mockRoots,...boundaryRoots,...extra]);
        const styles=chunkStyles(closure);
        return [...closure,...styles,...assessmentFonts(bundle,styles)].map(fileName=>`/${fileName}`).sort();
      };
      const mockAssets=mockPack(moduleRoots(/\/literacyMockRuntimeV10\.generated\.js$/));
      // Current mixed sittings never download historical publications or the
      // full authoring graph. Older sessions and exact-task fresh checks keep
      // their own complete executable closure, including their frozen bank.
      const legacyRoots=moduleRoots(/\/literacyMockBank\.js$/);
      const mockByVersion=Object.fromEntries(Array.from({length:10},(_,index)=>{
        const version=index+1;
        return [`literacy-mock-v${version}`,mockPack([...legacyRoots,...(version<=3
          ? moduleRoots(new RegExp(`/literacyMockV${version}\\.generated\\.js$`)):[])])];
      }));
      const selected = new Set([...selectedChunks].map(fileName => `/${fileName}`));
      for (const fileName of chunkStyles(selectedChunks)) selected.add(`/${fileName}`);
      selected.add("/index.html");
      if (includeQuestPreview) {
        selected.add("/preview/quest.html");
        selected.add("/preview/quest-evidence.html");
      }

      for (const item of Object.values(bundle)) {
        if (item.type !== "asset" || !item.fileName.endsWith(".html")) continue;
        selected.add(`/${item.fileName}`);
        const html = String(item.source || "");
        for (const match of html.matchAll(/(?:src|href)="(\/[^"?#]+)[^"]*"/g)) {
          if (match[1].startsWith("/assets/")) selected.add(match[1]);
        }
      }
      selected.add("/favicon.svg");
      selected.add("/apple-touch-icon.png");
      selected.add("/app-icon-512.png");
      selected.add("/icons.svg");
      selected.add("/manifest.webmanifest");

      const fingerprint = createHash("sha256");
      fingerprint.update(String(buildVariant));
      for (const url of [...selected].sort()) {
        fingerprint.update(url);
        const item = bundle[url.slice(1)];
        if (item?.type === "chunk") fingerprint.update(item.code || "");
        if (item?.type === "asset") fingerprint.update(String(item.source || ""));
      }
      const buildId = fingerprint.digest("hex").slice(0, 16);
      const precache = [...selected].sort();

      const manifest = webAppManifest();
      this.emitFile({ type: "asset", fileName: "manifest.webmanifest", source: `${JSON.stringify(manifest, null, 2)}\n` });
      this.emitFile({
        type: "asset",
        fileName: "offline-build.json",
        source: `${JSON.stringify({
          buildId,
          precache,
          executablePolicy: "build-versioned",
          questMediaPolicy: "cache-while-revalidate",
          updatePolicy: "activate-after-existing-clients-close",
          questExecutable,
          mockExecutable:{contentVersion:"literacy-mock-v10",planKind:"mixed",assets:mockAssets,byVersion:mockByVersion}
        }, null, 2)}\n`
      });
      this.emitFile({ type: "asset", fileName: "sw.js", source: serviceWorkerSource({ buildId, precache, questAssets, mockAssets }) });
    } }
  };
}

