export const V10_SCHEMA_MIGRATION = '20261016184804_literacy_mock_boundary_v10.sql';
const root = new URL('../', import.meta.url);
const pins = [
  ['20261016141521_literacy_mock_boundary_v9.sql', 'fd9e68b0dc7716d71ac4a5c7f188c83262c356a013712febb2a42d7b4c5c674c'],
  ['20261016171110_literacy_mock_v9_delivery_validation_cache.sql', '1994f9887d6817c7236d5ed97648cdda3a3f0b981aab635189b7f1fd8ec0dc68'],
  ['20261016174740_literacy_mock_v9_rhyme_demand_quarantine.sql', '1993fc3c42cc508e40b861ad416d1c51a63f0d1eb7cc76845603f2db9496584e'],
];
const sqlText = value => `'${String(value).replaceAll("'", "''")}'`;
const json = value => `${sqlText(JSON.stringify(value))}::jsonb`;
const definitions = source => new Map([...source.matchAll(/create or replace function public\.(\w+)\([\s\S]*?\$\$;/g)].map(match => [match[1], match[0]]));
const replaceOnce = (source, before, after) => {
  assert.equal(source.split(before).length, 2, `Frozen V9 source no longer matches: ${before}`);
  return source.replace(before, after);
};
function sources() {
  return pins.map(([name, sha]) => {
    const source = fs.readFileSync(new URL(`supabase/migrations/${name}`, root), 'utf8');
    assert.equal(crypto.createHash('sha256').update(source).digest('hex'), sha, `Applied migration changed: ${name}`);
    return source;
  });
}
function extendBoundaryVersion(source) {
  assert.ok(source, 'Missing frozen function definition.');
  // Extend only SQL version lists and comparisons; a literal followed by a
  // closing parenthesis may be an equality rather than a version list.
  const lists = source.replace(/\bin\s*\(([^()]*'literacy-mock-v9'[^()]*)\)/gi, (whole, values) =>
    values.includes("'literacy-mock-v10'") ? whole : whole.replace(values, `${values},'literacy-mock-v10'`));
  return lists.replace(/(v_mock->>'content_version'|v_version|(?:\w+\.)?content_version)\s*(=|<>)\s*'literacy-mock-v9'/g,
    (_whole, field, operator) => `${field} ${operator === '=' ? 'in' : 'not in'} ('literacy-mock-v9','literacy-mock-v10')`);
}

export function literacyMockV10QualitySql() {
  const rows = [
    ...LITERACY_QUARANTINED_ITEM_IDS.map(id => ({ id, issue: literacyItemQualityIssue({ id }), context: null })),
    ...LITERACY_CONTEXTUAL_ITEM_QUALITY_ISSUES.map(({ id, issue, ...context }) => ({ id, issue, context })),
  ];
  const values = rows.map(({ id, issue, context }) => `  (${sqlText(id)},${json(issue)},${context === null ? 'null::jsonb' : json(context)})`).join(',\n');
  return `create or replace function public.lp_literacy_item_quality_issue(p_value jsonb)
returns jsonb language sql immutable set search_path='' as $$
 with source as (select coalesce(nullif(p_value->'itemSnapshot','null'::jsonb),nullif(p_value->'questionSnapshot','null'::jsonb),nullif(p_value->'question','null'::jsonb),p_value) s),
 reviewed(id,issue,context) as (values
${values})
 select reviewed.issue from reviewed cross join source
 where reviewed.id=any(array[p_value->>'questionId',p_value->>'id',s->>'id',p_value->>'sourceItemId',s->>'sourceItemId'])
  and (reviewed.context is null or (s->>'adaptiveAreaVersion'=reviewed.context->>'adaptiveAreaVersion'
   and s->'adaptiveAreaBand'=reviewed.context->'adaptiveAreaBand'
   and (not reviewed.context ? 'contentVersion' or s->>'contentVersion'=reviewed.context->>'contentVersion')))
 limit 1;
$$;`;
}

/** Forward extension of the exact applied V9 chain. The boundary algorithm,
 * cached support projection, first-answer guards and historical banks remain. */
export function literacyMockV10SchemaSql() {
  const [boundary, cache] = sources();
  const original = definitions(boundary), latest = new Map([...original, ...definitions(cache)]);
  const ddl = boundary.slice(boundary.indexOf('alter table'), boundary.indexOf('\ndo $$declare v_name text;'));
  const replacements = [
    'lp_guard_literacy_mock_run', 'lp_progress_config_valid', 'lp_literacy_mock_assignment', 'lp_prepare_literacy_mock_focus',
    'lp_mock_state_before_delivery', 'lp_mock_run_before_delivery', 'lp_mock_support_before_delivery', 'lp_literacy_mock_state',
    'teacher_control_literacy_mock_session', 'student_sync_literacy_mock_batch', 'student_save_literacy_mock_run',
    'student_record_literacy_mock_event', 'lp_mock_area_next_band', 'lp_mock_area_plan_error',
  ];
  const parts = [
    '-- Generated by tools/generateLiteracyMockV10.mjs. Applied V1–V9 migrations, publications and raw answers remain immutable.\nbegin;',
    extendBoundaryVersion(ddl),
    ...replacements.map(name => extendBoundaryVersion(latest.get(name))),
  ];
  let rows = latest.get('lp_mock_boundary_rows_v9');
  rows = replaceOnce(rows, 'from public.literacy_mock_runs run cross join lateral',
    'from public.literacy_mock_runs run join public.student_focus_sessions boundary_focus on boundary_focus.id=run.session_id cross join lateral');
  rows = replaceOnce(rows, "i.content_version='literacy-mock-v9'", 'i.content_version=boundary_focus.content_version');
  parts.push(rows);
  let plan = latest.get('lp_mock_boundary_plan_error_v9');
  plan = replaceOnce(plan, 'declare v_rows jsonb',
    "declare v_version text:=(select content_version from public.student_focus_sessions where id=p_session_id); v_rows jsonb");
  assert.equal(plan.split("content_version='literacy-mock-v9'").length, 5, 'Expected four canonical plan lookups.');
  plan = plan.replaceAll("content_version='literacy-mock-v9'", 'content_version=v_version');
  parts.push(plan);
  for (const name of ['lp_mock_prepare_v9_before_delivery', 'teacher_prepare_literacy_mock_session_v9']) {
    parts.push(original.get(name).replaceAll('lp_mock_prepare_v9_before_delivery', 'lp_mock_prepare_v10_before_delivery')
      .replaceAll('teacher_prepare_literacy_mock_session_v9', 'teacher_prepare_literacy_mock_session_v10')
      .replaceAll('literacy-mock-v9', 'literacy-mock-v10').replaceAll('mock_v9_unavailable', 'mock_v10_unavailable'));
  }
  parts.push(literacyMockV10QualitySql());
  const contracts = definitions(parts.join('\n'));
  assert.equal(contracts.size, 19, 'The reviewed V10 surface has seventeen replacements and two new preparation functions.');
  const grants = [...contracts.values()].map(source => {
    const [name, args] = source.match(/function public\.(\w+)\(([\s\S]*?)\)\s*returns/).slice(1);
    const types = args.split(',').map(value => value.trim()).filter(Boolean).map(value => value.replace(/\s+default\b[\s\S]*/i, '').replace(/^\w+\s+/, '').trim());
    const signature = `public.${name}(${types.join(',')})`;
    const recipients = name.startsWith('student_') ? 'anon,authenticated' : name.startsWith('teacher_') ? 'authenticated' : null;
    return `revoke all on function ${signature} from public,anon,authenticated;${recipients ? `\ngrant execute on function ${signature} to ${recipients};` : ''}`;
  });
  parts.push(...grants, "notify pgrst, 'reload schema';\ncommit;");
  return parts.join('\n\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outputs = [[V10_SCHEMA_MIGRATION, literacyMockV10SchemaSql()]];
  if (!process.argv.includes('--schema-only')) outputs.push([V10_CATALOGUE_MIGRATION, await literacyMockV10CatalogueSql()]);
  for (const [name, sql] of outputs) {
    const file = new URL(`supabase/migrations/${name}`, root);
    if (process.argv.includes('--check')) assert.equal(fs.readFileSync(file, 'utf8'), sql, `Stale generated V10 migration: ${name}`);
    else fs.writeFileSync(file, sql);
  }
  console.log('V10 forward schema and publication sources match.');
}
