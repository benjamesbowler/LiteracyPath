import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { literacyMockV7SchemaSql } from './generateLiteracyMockV7.mjs';
import { createLiteracyMockManifest, compactIncomingSql } from './generateLiteracyMockManifest.mjs';
import { LITERACY_MOCK_V8_LADDERS } from '../src/policy/literacyMockDemandV8.js';
import { literacyMockIdentityV8Sql } from './literacyMockIdentityV8Sql.mjs';

const root = new URL('../', import.meta.url);
const definitions = new Map([...literacyMockV7SchemaSql().matchAll(/create or replace function public\.(\w+)\([\s\S]*?\$\$;/g)].map(m => [m[1], m[0]]));
const expand = source => source.replaceAll("'literacy-mock-v7')", "'literacy-mock-v7','literacy-mock-v8')");

export function literacyMockV8SchemaSql() {
  const previous = literacyMockV7SchemaSql();
  const parts = [expand(previous.slice(0, previous.indexOf('\n\ncreate or replace function'))
    .replace('Frozen v1-v6', 'Frozen v1-v7').replace('generateLiteracyMockV7.mjs', 'generateLiteracyMockV8.mjs'))];
  const names = ['lp_progress_config_valid','lp_literacy_mock_assignment','lp_prepare_literacy_mock_focus','lp_mock_state_before_delivery','lp_mock_run_before_delivery','lp_mock_support_before_delivery','lp_literacy_mock_state','teacher_control_literacy_mock_session','student_sync_literacy_mock_batch','student_save_literacy_mock_run','student_record_literacy_mock_event','lp_mock_area_band','lp_mock_area_next_band','lp_mock_area_plan_error'];
  for (const name of names) {
    let source = expand(definitions.get(name));
    if (name === 'lp_mock_area_band') source = source.replace("in ('areas-v1','areas-v2','areas-v3')", "in ('areas-v1','areas-v2','areas-v3','areas-v4')");
    if (name === 'lp_mock_area_plan_error') source = source.replace("case when v_version='literacy-mock-v7' then 'areas-v3'", "case when v_version='literacy-mock-v8' then 'areas-v4' when v_version='literacy-mock-v7' then 'areas-v3'");
    if (name === 'student_save_literacy_mock_run') {
      // A sitting downloaded before this migration may already contain two
      // formerly distinct aliases. Retain its authorized, unchanged slots;
      // every new/replaced slot and every V8 plan uses the stricter identity.
      const check = source.match(/ {4}if v_version[^\n]+fresh_sampling'='true' and exists\([\s\S]*?repeated_exposure_identity[^\n]+/)[0];
      const compatible = check.replace("jsonb_array_elements_text(p_plan->'itemIds') p(id)", "jsonb_array_elements_text(p_plan->'itemIds') with ordinality p(id,position)")
        .replace("having count(*)>1) then", "having count(*)>1 and (v_version='literacy-mock-v8' or not bool_and(v_run.session_id is not null and coalesce(p.id=v_run.plan->'itemIds'->>(p.position::integer-1),false)))) then");
      source = source.replace(check, compatible);
    }
    parts.push(source);
  }
  for (const name of ['lp_mock_prepare_v7_before_delivery','teacher_prepare_literacy_mock_session_v7']) parts.push(definitions.get(name)
    .replaceAll('lp_mock_prepare_v7_before_delivery','lp_mock_prepare_v8_before_delivery')
    .replaceAll('teacher_prepare_literacy_mock_session_v7','teacher_prepare_literacy_mock_session_v8')
    .replaceAll('literacy-mock-v7','literacy-mock-v8').replaceAll('mock_v7_unavailable','mock_v8_unavailable'));
  parts.push(literacyMockIdentityV8Sql());
  parts.push(previous.slice(previous.lastIndexOf('revoke all on function public.lp_progress_config_valid'))
    .replaceAll('lp_mock_prepare_v7_before_delivery','lp_mock_prepare_v8_before_delivery')
    .replaceAll('teacher_prepare_literacy_mock_session_v7','teacher_prepare_literacy_mock_session_v8'));
  return parts.join('\n\n').trimEnd() + '\n';
}

export async function literacyMockV8CatalogueSql() {
  const previous = await createLiteracyMockManifest({ contentVersion: 'literacy-mock-v7' });
  const manifest = await createLiteracyMockManifest({ contentVersion: 'literacy-mock-v8' });
  const oldIds = new Set(previous.items.map(q => q.id));
  const additions = manifest.items.filter(q => !oldIds.has(q.id));
  if (oldIds.size + additions.length !== manifest.itemCount) throw Error('V8 must retain every prior item identity.');
  const bands = Object.fromEntries(manifest.items.filter(q => q.itemSnapshot.adaptiveMixedEligible).map(q => [q.id, q.itemSnapshot.adaptiveAreaBand]));
  const literal = value => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
  return `-- Generated by tools/generateLiteracyMockV8.mjs. Append material; preserve all older publications.
begin;
create temporary table literacy_mock_incoming(item jsonb not null) on commit drop;
${compactIncomingSql(additions)}
with source as (select item,item->'itemSnapshot' s from public.literacy_mock_items where content_version='literacy-mock-v7'),
route as (select ${literal(bands)} bands,${literal(LITERACY_MOCK_V8_LADDERS)} ladders),
classified as (select source.*,case when bands?(s->>'id') then (bands->>(s->>'id'))::integer else null end band,ladders from source cross join route),
snapshots as (select item,s||jsonb_build_object('contentVersion','literacy-mock-v8','adaptiveAreaVersion','areas-v4','adaptiveAreaBand',band,'adaptiveMixedEligible',band is not null,'adaptiveDemand',case when band is null then 'null'::jsonb else ladders->(s->>'domainId')->band end) snapshot from classified)
insert into literacy_mock_incoming select jsonb_set(item,'{itemSnapshot}',snapshot) from snapshots;
do $$begin
 if (select count(*) from public.literacy_mock_items where content_version='literacy-mock-v7')<>${previous.itemCount} or (select count(*) from literacy_mock_incoming)<>${manifest.itemCount} then raise exception 'Incomplete V8 publication'; end if;
 if exists(select 1 from literacy_mock_incoming incoming join public.literacy_mock_items old on old.id=incoming.item->>'id' and old.content_version='literacy-mock-v8' where old.item is distinct from incoming.item) then raise exception 'Cannot rewrite immutable V8 publication'; end if;
end; $$;
insert into public.literacy_mock_items(id,content_version,item) select item->>'id','literacy-mock-v8',item from literacy_mock_incoming on conflict(id,content_version) do nothing;
insert into public.literacy_mock_publications(content_version,item_count) values('literacy-mock-v8',${manifest.itemCount}) on conflict(content_version) do nothing;
do $$begin
 if (select count(*) from public.literacy_mock_items where content_version='literacy-mock-v8')<>${manifest.itemCount} or not exists(select 1 from public.literacy_mock_publications where content_version='literacy-mock-v8' and item_count=${manifest.itemCount}) then raise exception 'V8 publication count mismatch'; end if;
end; $$;
commit;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outputs = [['supabase/migrations/20261016062452_literacy_mock_retake_v8.sql', literacyMockV8SchemaSql()],
    ['supabase/migrations/20261016062517_literacy_mock_catalogue_v8.sql', await literacyMockV8CatalogueSql()]];
  for (const [name, sql] of outputs) {
    const path = new URL(name, root);
    if (process.argv.includes('--check')) { if (fs.readFileSync(path, 'utf8') !== sql) throw Error(`Stale generated V8 migration ${name}`); }
    else fs.writeFileSync(path, sql);
  }
  console.log('V8 schema and publication sources match.');
}
