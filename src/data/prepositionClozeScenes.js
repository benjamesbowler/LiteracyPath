export function sceneForPrepositionQuestion(preposition, index = 0) {
  const scenes = prepositionClozeScenes[String(preposition || "").toLowerCase()] || [];
  if (!scenes.length) return null;
  const [sentence, fullSentence, imagePath] = scenes[Math.abs(Number(index) || 0) % scenes.length];
  return { sentence, fullSentence, imagePath };
}
