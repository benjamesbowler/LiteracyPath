export function applyLiteracyMockFoundationMediaReview(item) {
  const paths = [...new Set([item.image, ...(item.requiredImagePaths || []),
    ...(item.choices || []).map(choice => choice.image)].filter(path =>
    path?.startsWith('/images/assessment/literacy-mock/capacity/foundation-')))];
  if (!paths.length) return item;
  const reviewedAssets = paths.filter(path => REVIEWED_MOCK_FOUNDATION_MEDIA[path])
    .map(path => ({ path, sha256: REVIEWED_MOCK_FOUNDATION_MEDIA[path].sha256 }));
  return { ...item, mediaDecision: { ...item.mediaDecision,
    constructReview: reviewedAssets.length === paths.length ? 'approved' : 'pending',
    reviewedAssets, reviewType: 'independent_visual_model_review',
  } };
}
