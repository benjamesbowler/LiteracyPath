export function addSectionHeading(sheet, row, title, help = "", { startColumn = 2, span = 12 } = {}) {
  const colLetter = n => sheet.getColumn(n).letter;
  sheet.mergeCells(`${colLetter(startColumn)}${row}:${colLetter(startColumn + span - 1)}${row}`);
  writeCell(sheet, `${colLetter(startColumn)}${row}`, title, {
    font: WORKBOOK_FONTS.sectionTitle,
    alignment: { vertical: "middle" }
  });
  sheet.getRow(row).height = 22;
  let next = row + 1;
  if (help) {
    sheet.mergeCells(`${colLetter(startColumn)}${next}:${colLetter(startColumn + span - 1)}${next}`);
    writeCell(sheet, `${colLetter(startColumn)}${next}`, help, {
      font: WORKBOOK_FONTS.sectionHelp,
      alignment: { vertical: "top", wrapText: true }
    });
    sheet.getRow(next).height = Math.max(15, Math.ceil(String(help).length / 110) * 14);
    next += 1;
  }
  return next + 1;
}

