/**
 * The workbook kit.
 *
 * A workbook is a report that happens to be in Excel. It carries the same
 * summary block, the same vocabulary, the same colours and the same next-step
 * guidance as the screen — Reporting Bible, Part X.
 *
 * Before this kit, every export was a flat provenance dump: a 29-column sheet
 * whose headers included "Response schema", "Scoring rule version" and
 * "Administration interface", with no cover, no summary, no next step, and
 * export-only synonyms ("Growing", "Not started yet") that contradicted the
 * screen. That is an audit log, not a report. This kit builds the report.
 *
 * Nothing here knows about literacy. It knows about cover sheets, KPI bands,
 * tables, matrices and legends. The report builders supply the content.
 */

