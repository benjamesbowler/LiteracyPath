export async function workbookToBuffer(workbook) {
  return workbook.xlsx.writeBuffer();
}

export async function downloadWorkbook(workbook, fileName) {
  const buffer = await workbookToBuffer(workbook);
  if (typeof document === "undefined" || typeof URL?.createObjectURL !== "function") {
    return buffer;
  }
  const blob = new Blob([buffer], {
    type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
  });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = fileName;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
  return buffer;
}

/**
 * Put the sheets in reading order regardless of the order they were built in.
 * ExcelJS orders by insertion; report builders often create detail sheets while
 * they still have the data in hand.
 */
export function orderSheets(workbook, preferredOrder = []) {
  const order = new Map(preferredOrder.map((name, index) => [name, index]));
  workbook.worksheets
    .slice()
    .sort((a, b) => {
      const aOrder = order.has(a.name) ? order.get(a.name) : 500;
      const bOrder = order.has(b.name) ? order.get(b.name) : 500;
      return aOrder - bOrder;
    })
    .forEach((sheet, index) => {
      sheet.orderNo = index + 1;
    });
}
