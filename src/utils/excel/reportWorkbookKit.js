/**
 * A students × skills grid. Cells carry the status mark and are coloured from
 * the canonical status id — never from a percentage, because the band comes
 * from status, not accuracy, and a 100%-accuracy cell can legitimately be
 * neutral (see `simpleStudentReports.js` and the bible, Part X.3).
 *
 * The row header column is frozen so a teacher can scroll a wide matrix and
 * still see who each row is.
 */
export function addStatusMatrix(sheet, startRow, {
  rowHeader = "Student",
  columnHeaders = [],
  rows = [],
  startColumn = 2,
  emptyMessage = "No results yet.",
  // Long headers print on the diagonal, which is the only way a thirty-column
  // class matrix fits a page. With a handful of columns it just looks broken —
  // and worse, a 12-character header sits flat immediately beside a
  // 13-character one standing on its end. Callers with few columns raise this.
  rotateHeadersOver = 12,
  columnWidth = 13
} = {}) {
  const colLetter = n => sheet.getColumn(n).letter;
  const rotates = header => String(header).length > rotateHeadersOver;

  writeCell(sheet, `${colLetter(startColumn)}${startRow}`, rowHeader, {
    font: WORKBOOK_FONTS.tableHeader,
    fill: WORKBOOK_COLORS.primaryStrong,
    alignment: { vertical: "middle", wrapText: true }
  });
  sheet.getColumn(startColumn).width = Math.max(
    18,
    Math.min(34, rows.reduce((widest, row) => Math.max(widest, String(row.label || "").length), rowHeader.length) + 2)
  );

  // ALL OR NONE. Deciding per header meant "Short a CVC" lay flat beside
  // "Letter sounds a-m" standing on its end in the same row, which reads as a
  // rendering fault rather than a space-saving choice. One long name is enough
  // to tip the whole header row onto the diagonal.
  const anyRotates = columnHeaders.some(rotates);

  columnHeaders.forEach((header, index) => {
    const position = startColumn + 1 + index;
    writeCell(sheet, `${colLetter(position)}${startRow}`, header, {
      font: WORKBOOK_FONTS.tableHeader,
      fill: WORKBOOK_COLORS.primaryStrong,
      alignment: { vertical: "bottom", horizontal: "center", wrapText: true, textRotation: anyRotates ? 60 : 0 }
    });
    sheet.getColumn(position).width = Math.max(
      columnWidth,
      anyRotates ? columnWidth : String(header).length + 2
    );
  });
  sheet.getRow(startRow).height = anyRotates ? 74 : 28;

  if (!rows.length) {
    writeCell(sheet, `${colLetter(startColumn)}${startRow + 1}`, emptyMessage, {
      font: { ...WORKBOOK_FONTS.bodyMuted, italic: true }
    });
    return startRow + 3;
  }

  rows.forEach((row, rowIndex) => {
    const excelRow = startRow + 1 + rowIndex;
    writeCell(sheet, `${colLetter(startColumn)}${excelRow}`, row.label ?? "", {
      font: { ...WORKBOOK_FONTS.body, bold: true },
      fill: rowIndex % 2 ? WORKBOOK_COLORS.surfaceSubtle : undefined,
      alignment: { vertical: "middle" },
      border: { bottom: thin(WORKBOOK_COLORS.border) }
    });
    (row.cells || []).forEach((cellValue, index) => {
      const position = startColumn + 1 + index;
      const id = canonicalStatusId(cellValue?.status ?? cellValue);
      const treatment = statusCellStyle(id);
      const cell = writeCell(sheet, `${colLetter(position)}${excelRow}`, treatment.mark, {
        font: { ...WORKBOOK_FONTS.body, bold: true, size: 12, color: { argb: treatment.font } },
        fill: treatment.fill,
        alignment: { vertical: "middle", horizontal: "center" },
        border: boxBorder(treatment.edge)
      });
      const detail = cellValue?.note || cellValue?.detail;
      cell.note = detail
        ? `${reportStatusLabel(id)} — ${detail}`
        : reportStatusLabel(id);
    });
    sheet.getRow(excelRow).height = 20;
  });

  sheet.views = [{ state: "frozen", ySplit: startRow, xSplit: startColumn, showGridLines: false }];
  return startRow + rows.length + 3;
}

/**
 * A numeric heatmap with a real Excel three-colour scale, for anything that IS
 * legitimately continuous (coverage percentages, counts). Never used for status.
 */
export function addNumericHeatmap(sheet, { firstRow, lastRow, firstColumn, lastColumn, reverse = false }) {
  const colLetter = n => sheet.getColumn(n).letter;
  const ref = `${colLetter(firstColumn)}${firstRow}:${colLetter(lastColumn)}${lastRow}`;
  const low = reverse ? WORKBOOK_COLORS.secureFill : WORKBOOK_COLORS.needsSupportFill;
  const high = reverse ? WORKBOOK_COLORS.needsSupportFill : WORKBOOK_COLORS.secureFill;
  sheet.addConditionalFormatting({
    ref,
    rules: [{
      type: "colorScale",
      priority: 1,
      cfvo: [{ type: "min" }, { type: "percentile", value: 50 }, { type: "max" }],
      color: [{ argb: low }, { argb: WORKBOOK_COLORS.developingFill }, { argb: high }]
    }]
  });
  return ref;
}

