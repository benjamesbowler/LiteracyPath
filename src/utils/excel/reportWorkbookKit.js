/**
 * Numeric columns are right-aligned with a one-character indent. Without the
 * indent a narrow count column pushes its digits flush against the next
 * column's text, and "3" beside "Multisensory ch/sh/th sort" reads as one value.
 */
function numericColumn(column) {
  return column?.type === "number" || column?.type === "percent";
}

/**
 * Column spec:
 *   { key, header, width?, type?, wrap?, note? }
 *   type: "text" | "number" | "percent" | "date" | "status" | "fraction"
 *
 * `type: "status"` colours the cell from the canonical status id and prefixes
 * the mark glyph, so the sheet still reads in greyscale.
 *
 * Widths are computed from actual content when not given, capped at 60 —
 * ExcelJS will not autofit, and 29 columns of default width is why the old
 * exports were unreadable without ten minutes of dragging.
 */
export function addTable(sheet, startRow, columns = [], rows = [], {
  startColumn = 2,
  zebra = true,
  autoFilter = true,
  freezeHeader = true,
  freezeFirstColumn = false,
  emptyMessage = "No results yet.",
  totalRow = null
} = {}) {
  const colLetter = n => sheet.getColumn(n).letter;
  const headerRow = startRow;

  columns.forEach((column, index) => {
    const position = startColumn + index;
    const cell = writeCell(sheet, `${colLetter(position)}${headerRow}`, column.header, {
      font: WORKBOOK_FONTS.tableHeader,
      fill: WORKBOOK_COLORS.primaryStrong,
      alignment: numericColumn(column)
        ? { vertical: "middle", horizontal: "right", indent: 1, wrapText: true }
        : { vertical: "middle", horizontal: "left", indent: 1, wrapText: true },
      border: { bottom: thin(WORKBOOK_COLORS.primary) }
    });
    if (column.note) cell.note = column.note;

    const contentWidth = rows.reduce((widest, row) => {
      const value = row?.[column.key];
      const text = value === null || value === undefined ? "" : String(value);
      return Math.max(widest, Math.min(text.length, column.wrap ? 44 : 60));
    }, String(column.header).length);
    sheet.getColumn(position).width =
      column.width || Math.max(numericColumn(column) ? 14 : 10, Math.min(60, contentWidth + 3));
  });
  sheet.getRow(headerRow).height = 26;

  if (!rows.length) {
    sheet.mergeCells(
      `${colLetter(startColumn)}${headerRow + 1}:${colLetter(startColumn + Math.max(0, columns.length - 1))}${headerRow + 1}`
    );
    writeCell(sheet, `${colLetter(startColumn)}${headerRow + 1}`, emptyMessage, {
      font: { ...WORKBOOK_FONTS.bodyMuted, italic: true },
      alignment: { vertical: "middle", wrapText: true }
    });
    return { headerRow, firstDataRow: headerRow + 1, lastRow: headerRow + 1, nextRow: headerRow + 3 };
  }

  rows.forEach((row, rowIndex) => {
    const excelRow = headerRow + 1 + rowIndex;
    const striped = zebra && rowIndex % 2 === 1;
    columns.forEach((column, index) => {
      const position = startColumn + index;
      const raw = row?.[column.key];
      const style = {
        font: WORKBOOK_FONTS.body,
        alignment: numericColumn(column)
          ? { vertical: "top", horizontal: "right", indent: 1 }
          : { vertical: "top", horizontal: "left", indent: 1, wrapText: Boolean(column.wrap) },
        border: { bottom: thin(WORKBOOK_COLORS.border) }
      };
      if (striped) style.fill = WORKBOOK_COLORS.surfaceSubtle;

      let value = raw;
      if (column.type === "number") {
        value = numberOrBlank(raw);
        style.numFmt = column.numFmt || NUMBER_FORMATS.integer;
      } else if (column.type === "percent") {
        value = percentOrBlank(raw);
        style.numFmt = column.numFmt || NUMBER_FORMATS.percent;
      } else if (column.type === "date") {
        value = dateOrBlank(raw);
      } else if (column.type === "status") {
        const id = canonicalStatusId(raw);
        const treatment = statusCellStyle(id);
        value = `${treatment.mark}  ${reportStatusLabel(id)}`;
        style.fill = treatment.fill;
        style.font = { ...WORKBOOK_FONTS.body, bold: true, color: { argb: treatment.font } };
        style.border = { ...style.border, ...boxBorder(treatment.edge) };
      } else if (value === null || value === undefined) {
        value = "";
      }
      writeCell(sheet, `${colLetter(position)}${excelRow}`, value, style);
    });
    if (columns.some(column => column.wrap)) {
      const longest = columns
        .filter(column => column.wrap)
        .reduce((max, column) => Math.max(max, String(row?.[column.key] ?? "").length), 0);
      const width = columns.find(column => column.wrap)?.width || 44;
      sheet.getRow(excelRow).height = Math.max(18, Math.min(90, Math.ceil(longest / width) * 13 + 5));
    }
  });

  const lastRow = headerRow + rows.length;
  let nextRow = lastRow + 1;

  if (totalRow) {
    columns.forEach((column, index) => {
      const position = startColumn + index;
      const raw = totalRow[column.key];
      const style = {
        font: { ...WORKBOOK_FONTS.body, bold: true },
        fill: WORKBOOK_COLORS.primarySoft,
        alignment: numericColumn(column)
          ? { vertical: "middle", horizontal: "right", indent: 1 }
          : { vertical: "middle", horizontal: "left", indent: 1 },
        border: { top: thin(WORKBOOK_COLORS.primary), bottom: thin(WORKBOOK_COLORS.primary) }
      };
      let value = raw ?? "";
      if (column.type === "number") {
        value = numberOrBlank(raw);
        style.numFmt = column.numFmt || NUMBER_FORMATS.integer;
      } else if (column.type === "percent") {
        value = percentOrBlank(raw);
        style.numFmt = column.numFmt || NUMBER_FORMATS.percent;
      }
      writeCell(sheet, `${colLetter(position)}${nextRow}`, value, style);
    });
    nextRow += 1;
  }

  if (autoFilter) {
    sheet.autoFilter = {
      from: { row: headerRow, column: startColumn },
      to: { row: lastRow, column: startColumn + columns.length - 1 }
    };
  }
  if (freezeHeader) {
    sheet.views = [{
      state: "frozen",
      ySplit: headerRow,
      xSplit: freezeFirstColumn ? startColumn : 0,
      showGridLines: false
    }];
  }

  return { headerRow, firstDataRow: headerRow + 1, lastRow, nextRow: nextRow + 1 };
}

