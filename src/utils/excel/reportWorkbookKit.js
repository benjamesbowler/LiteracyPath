/**
 * The cover. Hambleton & Zenisky's most actionable finding is that every report
 * needs a highlight block at the top saying what it says — the field's weakest
 * domain is supporting material, at 1.28 out of 3.0.
 */
export function addCoverSheet(workbook, {
  eyebrow = "Literacy Guide",
  title = "Report",
  subtitle = "",
  headline = "",
  facts = [],
  notices = [],
  taken
} = {}) {
  const sheet = addSheet(workbook, SHEET_NAMES.COVER, { tabColor: WORKBOOK_COLORS.primary, taken });
  sheet.columns = [{ width: 3 }, { width: 26 }, { width: 62 }, { width: 3 }];

  sheet.mergeCells("B2:C2");
  writeCell(sheet, "B2", eyebrow.toUpperCase(), { font: WORKBOOK_FONTS.coverEyebrow });

  sheet.mergeCells("B3:C4");
  writeCell(sheet, "B3", title, {
    font: WORKBOOK_FONTS.coverTitle,
    alignment: { vertical: "middle", wrapText: true }
  });
  sheet.getRow(3).height = 30;
  sheet.getRow(4).height = 12;

  if (subtitle) {
    sheet.mergeCells("B5:C5");
    writeCell(sheet, "B5", subtitle, { font: WORKBOOK_FONTS.coverSubtitle, alignment: { wrapText: true } });
  }

  // A rule under the title block, in brand teal.
  ["B6", "C6"].forEach(address => {
    writeCell(sheet, address, "", { fill: WORKBOOK_COLORS.primary });
  });
  sheet.getRow(6).height = 3;

  let row = 8;
  if (headline) {
    sheet.mergeCells(`B${row}:C${row + 2}`);
    writeCell(sheet, `B${row}`, headline, {
      font: { ...WORKBOOK_FONTS.body, size: 12 },
      fill: WORKBOOK_COLORS.primarySoft,
      border: boxBorder(WORKBOOK_COLORS.border),
      alignment: { vertical: "top", wrapText: true }
    });
    sheet.getRow(row).height = 22;
    sheet.getRow(row + 1).height = 22;
    sheet.getRow(row + 2).height = 22;
    row += 4;
  }

  facts.filter(Boolean).forEach(([label, value]) => {
    writeCell(sheet, `B${row}`, label, { font: WORKBOOK_FONTS.kpiLabel, alignment: { vertical: "top" } });
    // Left-align explicitly: Excel right-aligns numbers by default, which would
    // strand a bare count at the far edge of a wide column, disconnected from
    // the label it belongs to.
    writeCell(sheet, `C${row}`, value ?? "", {
      font: WORKBOOK_FONTS.body,
      alignment: { vertical: "top", horizontal: "left", wrapText: true }
    });
    row += 1;
  });

  row += 1;
  [...notices, REPORTING_BIBLE_POLICY.exportPrivacy.confidentialityBanner,
    REPORTING_BIBLE_POLICY.exportPrivacy.releaseNotice]
    .filter(Boolean)
    .forEach(notice => {
      sheet.mergeCells(`B${row}:C${row}`);
      writeCell(sheet, `B${row}`, notice, {
        font: WORKBOOK_FONTS.banner,
        alignment: { vertical: "top", wrapText: true }
      });
      sheet.getRow(row).height = Math.max(14, Math.ceil(String(notice).length / 95) * 12);
      row += 1;
    });

  sheet.views = [{ showGridLines: false }];
  applyPrintSetup(sheet, { titleForFooter: title });
  return sheet;
}

