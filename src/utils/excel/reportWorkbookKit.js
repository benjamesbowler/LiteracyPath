const KPI_TONES = Object.freeze({
  neutral: { fill: WORKBOOK_COLORS.surfaceSubtle, edge: WORKBOOK_COLORS.border, text: WORKBOOK_COLORS.inkStrong },
  brand: { fill: WORKBOOK_COLORS.primarySoft, edge: WORKBOOK_COLORS.primary, text: WORKBOOK_COLORS.primaryStrong },
  secure: { fill: WORKBOOK_COLORS.secureFill, edge: WORKBOOK_COLORS.secureEdge, text: WORKBOOK_COLORS.secureText },
  developing: { fill: WORKBOOK_COLORS.developingFill, edge: WORKBOOK_COLORS.developingEdge, text: WORKBOOK_COLORS.developingText },
  needs_support: { fill: WORKBOOK_COLORS.needsSupportFill, edge: WORKBOOK_COLORS.needsSupportEdge, text: WORKBOOK_COLORS.needsSupportText },
  mixed_evidence: { fill: WORKBOOK_COLORS.mixedFill, edge: WORKBOOK_COLORS.mixedEdge, text: WORKBOOK_COLORS.mixedText },
  not_enough_evidence: { fill: WORKBOOK_COLORS.neutralFill, edge: WORKBOOK_COLORS.neutralEdge, text: WORKBOOK_COLORS.neutralText },
  not_checked: { fill: WORKBOOK_COLORS.neutralFill, edge: WORKBOOK_COLORS.neutralEdge, text: WORKBOOK_COLORS.neutralText }
});

/**
 * A row of metric cards, each spanning two columns and three rows — the
 * screen's `.simple-report-summary` in cells.
 *
 * A card whose `value` is null renders "Not enough results", never 0.
 */
export function addKpiBand(sheet, startRow, cards = [], { columnsPerCard = 2, startColumn = 2 } = {}) {
  const usable = cards.filter(Boolean).slice(0, 6);
  usable.forEach((card, index) => {
    const first = startColumn + index * columnsPerCard;
    const last = first + columnsPerCard - 1;
    const tone = KPI_TONES[card.tone] || KPI_TONES.neutral;
    const colLetter = n => sheet.getColumn(n).letter;

    sheet.mergeCells(`${colLetter(first)}${startRow}:${colLetter(last)}${startRow}`);
    writeCell(sheet, `${colLetter(first)}${startRow}`, String(card.label || "").toUpperCase(), {
      font: { ...WORKBOOK_FONTS.kpiLabel, color: { argb: tone.text } },
      fill: tone.fill,
      border: { top: thin(tone.edge), left: thin(tone.edge), right: thin(tone.edge) },
      alignment: { vertical: "middle", horizontal: "left", indent: 1 }
    });

    sheet.mergeCells(`${colLetter(first)}${startRow + 1}:${colLetter(last)}${startRow + 1}`);
    const hasValue = card.value !== null && card.value !== undefined && card.value !== "";
    const valueCell = writeCell(
      sheet,
      `${colLetter(first)}${startRow + 1}`,
      hasValue ? card.value : "Not enough results",
      {
        font: hasValue
          ? { ...WORKBOOK_FONTS.kpiValue, color: { argb: tone.text } }
          : { ...WORKBOOK_FONTS.bodyMuted, italic: true },
        fill: tone.fill,
        border: { left: thin(tone.edge), right: thin(tone.edge) },
        alignment: { vertical: "middle", horizontal: "left", indent: 1 }
      }
    );
    if (hasValue && card.numFmt) valueCell.numFmt = card.numFmt;

    sheet.mergeCells(`${colLetter(first)}${startRow + 2}:${colLetter(last)}${startRow + 2}`);
    writeCell(sheet, `${colLetter(first)}${startRow + 2}`, card.note || "", {
      font: WORKBOOK_FONTS.kpiNote,
      fill: tone.fill,
      border: { bottom: thin(tone.edge), left: thin(tone.edge), right: thin(tone.edge) },
      alignment: { vertical: "top", horizontal: "left", indent: 1, wrapText: true }
    });
  });

  sheet.getRow(startRow).height = 16;
  sheet.getRow(startRow + 1).height = 30;
  sheet.getRow(startRow + 2).height = 26;
  return startRow + 4;
}

/**
 * The five/six-way status split, in the bible's order, with the reconcile line
 * beneath. `counts` is keyed by any status alias; it is canonicalised here.
 */
export function addStatusSplit(sheet, startRow, counts = {}, { reconcileLine = "", startColumn = 2 } = {}) {
  const normalised = {};
  Object.entries(counts).forEach(([key, value]) => {
    const id = canonicalStatusId(key);
    normalised[id] = (normalised[id] || 0) + (Number(value) || 0);
  });
  const cards = REPORT_STATUS_ORDER.filter(
    id => normalised[id] !== undefined || id !== "mixed_evidence"
  ).map(id => ({
    label: REPORT_STATUS_LABELS[id],
    value: normalised[id] || 0,
    note: REPORT_STATUS_NOTES[id],
    tone: id,
    numFmt: NUMBER_FORMATS.integer
  }));

  let row = addKpiBand(sheet, startRow, cards, { columnsPerCard: 2, startColumn });
  if (reconcileLine) {
    const colLetter = n => sheet.getColumn(n).letter;
    sheet.mergeCells(`${colLetter(startColumn)}${row}:${colLetter(startColumn + 11)}${row}`);
    writeCell(sheet, `${colLetter(startColumn)}${row}`, reconcileLine, {
      font: WORKBOOK_FONTS.bodyMuted,
      alignment: { vertical: "middle", wrapText: true }
    });
    row += 2;
  }
  return row;
}

