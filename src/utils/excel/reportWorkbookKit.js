/** Excel forbids these in a sheet name, and caps the name at 31 characters. */
export function safeSheetName(name, taken = new Set()) {
  let base = String(name || "Sheet").replace(/[[\]:*?/\\]/g, " ").trim().slice(0, 31) || "Sheet";
  if (!taken.has(base)) {
    taken.add(base);
    return base;
  }
  for (let suffix = 2; suffix < 100; suffix += 1) {
    const candidate = `${base.slice(0, 31 - String(suffix).length - 1)} ${suffix}`;
    if (!taken.has(candidate)) {
      taken.add(candidate);
      return candidate;
    }
  }
  taken.add(base);
  return base;
}

async function loadExcelJs() {
  const module = await import("exceljs");
  const ExcelJS = module.default || module["module.exports"] || module;
  if (!ExcelJS?.Workbook) throw new Error("ExcelJS workbook export is unavailable.");
  return ExcelJS;
}

/* ------------------------------------------------------------------ *
 * Low-level cell helpers
 * ------------------------------------------------------------------ */

function fill(color) {
  return { type: "pattern", pattern: "solid", fgColor: { argb: color } };
}

function thin(color) {
  return { style: "thin", color: { argb: color } };
}

function boxBorder(color) {
  return { top: thin(color), left: thin(color), bottom: thin(color), right: thin(color) };
}

export function writeCell(sheet, address, value, style = {}) {
  const cell = sheet.getCell(address);
  cell.value = value === undefined || value === null ? "" : value;
  if (style.font) cell.font = style.font;
  if (style.fill) cell.fill = fill(style.fill);
  if (style.border) cell.border = style.border;
  if (style.alignment) cell.alignment = style.alignment;
  if (style.numFmt) cell.numFmt = style.numFmt;
  return cell;
}

/**
 * Values that must never render as 0.
 *
 * The bible's first law: missing evidence is reported as missing. Passing null
 * through `Number()` yields 0, and a 0 in an accuracy column reads as a child
 * who got everything wrong. Every numeric writer in this kit goes through here.
 */
export function numberOrBlank(value) {
  if (value === undefined || value === null || value === "") return "";
  const number = Number(value);
  return Number.isFinite(number) ? number : "";
}

export function percentOrBlank(value) {
  const number = numberOrBlank(value);
  return number === "" ? "" : number / 100;
}

export function dateOrBlank(value) {
  if (!value) return "";
  const date = value instanceof Date ? value : new Date(value);
  return Number.isNaN(date.getTime()) ? "" : date.toISOString().slice(0, 10);
}

